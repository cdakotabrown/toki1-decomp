#!/usr/bin/env python3
"""
permute_function.py - Decomp-permuter integration for finding byte-perfect matches

Wrapper around decomp-permuter that automates the process of finding
instruction reorderings and code variations that produce byte-perfect matches.

Features:
- Automatic setup of permuter directories
- Generates base.c and target.o for permuter
- Runs permutation search with configurable iterations
- Reports when perfect match is found
- Optionally saves successful variant back to source file

Usage:
    python3 tools/permute_function.py func_8004B338
    python3 tools/permute_function.py func_8004B338 --iterations 10000
    python3 tools/permute_function.py func_8004B338 --save-match
    python3 tools/permute_function.py func_8004B338 --show-base

Prerequisites:
    make setup-permuter

Documentation:
    https://github.com/simonlindholm/decomp-permuter
"""

import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Dict, Optional, Tuple

# Project paths
ROOT_DIR = Path(__file__).parent.parent
ORIGINAL_EXE = ROOT_DIR / "disks" / "SLPM_86.053"
FUNCTION_MAP = ROOT_DIR / "build" / "function_analysis" / "function_map.json"
DECOMP_CONFIG = ROOT_DIR / "config" / "decompiled_functions.json"
BUILD_DIR = ROOT_DIR / "build" / "jp"
PERMUTER_DIR = ROOT_DIR / "build" / "permuter"

# Constants
TEXT_SECTION_START = 0x80041000
FILE_OFFSET_BASE = 0x800


def load_function_map() -> Dict:
    """Load the function map."""
    if not FUNCTION_MAP.exists():
        print(f"Error: Function map not found at {FUNCTION_MAP}")
        print("Run: make analyze")
        sys.exit(1)

    with open(FUNCTION_MAP, 'r') as f:
        return json.load(f)


def load_decomp_config() -> Dict:
    """Load the decompiled functions configuration."""
    if not DECOMP_CONFIG.exists():
        print(f"Error: Decompiled functions config not found at {DECOMP_CONFIG}")
        sys.exit(1)

    with open(DECOMP_CONFIG, 'r') as f:
        return json.load(f)


def get_function_info(func_name: str, function_map: Dict) -> Optional[Dict]:
    """Get function metadata from the function map."""
    for func in function_map.get('functions', []):
        if func['name'] == func_name:
            return func
    return None


def vram_to_file_offset(vram_addr: int) -> int:
    """Convert VRAM address to file offset."""
    return (vram_addr - TEXT_SECTION_START) + FILE_OFFSET_BASE


def extract_original_bytes(vram_start: int, size: int) -> bytes:
    """Extract function bytes from the original executable."""
    file_offset = vram_to_file_offset(vram_start)

    with open(ORIGINAL_EXE, 'rb') as f:
        f.seek(file_offset)
        return f.read(size)


def create_target_object(func_name: str, vram_start: int, original_bytes: bytes,
                         output_dir: Path) -> Path:
    """
    Create a target.o file containing the original function bytes.

    The permuter needs this to compare against.
    """
    target_bin = output_dir / "target.bin"
    target_o = output_dir / "target.o"

    # Write raw bytes
    with open(target_bin, 'wb') as f:
        f.write(original_bytes)

    # Create a minimal ELF .o file with these bytes in .text
    # Using a simple assembly wrapper
    target_s = output_dir / "target.s"
    with open(target_s, 'w') as f:
        f.write(f".set noat\n")
        f.write(f".set noreorder\n")
        f.write(f".section .text\n")
        f.write(f".globl {func_name}\n")
        f.write(f"{func_name}:\n")

        # Write each word as .word directive
        for i in range(0, len(original_bytes), 4):
            word = int.from_bytes(original_bytes[i:i+4], 'little')
            f.write(f"    .word 0x{word:08x}\n")

    # Assemble to object file
    cmd = [
        "mipsel-linux-gnu-as",
        "-march=r3000", "-O0",
        "-o", str(target_o),
        str(target_s)
    ]

    result = subprocess.run(cmd, capture_output=True)
    if result.returncode != 0:
        print(f"Error creating target.o: {result.stderr.decode()}")
        sys.exit(1)

    return target_o


def get_source_content(source_file: str) -> str:
    """Read the C source file content."""
    source_path = ROOT_DIR / source_file
    if not source_path.exists():
        print(f"Error: Source file not found: {source_path}")
        sys.exit(1)

    with open(source_path, 'r') as f:
        return f.read()


def create_base_c(func_name: str, source_content: str, output_dir: Path) -> Path:
    """
    Create base.c file for the permuter.

    The permuter will generate variations of this file.
    """
    base_c = output_dir / "base.c"

    # Add permuter annotations
    permuter_content = f"""// Permuter base file for {func_name}
// Generated by permute_function.py

{source_content}
"""

    with open(base_c, 'w') as f:
        f.write(permuter_content)

    return base_c


def create_compile_script(output_dir: Path) -> Path:
    """
    Create the compile.sh script that the permuter uses.

    This must compile the C file to match our build system.
    """
    compile_sh = output_dir / "compile.sh"

    script_content = f"""#!/bin/bash
# Compile script for decomp-permuter
# Compiles C source to object file matching PSY-Q GCC 2.7 output

INPUT="$1"
OUTPUT="${{INPUT%.c}}.o"

# Preprocess
cpp -I{ROOT_DIR}/include -Iinclude -undef -Wall -lang-c -fno-builtin "$INPUT" > "${{INPUT%.c}}.i"

# Compile with cc1-psx-26
{ROOT_DIR}/tools/psyq-gcc-260/cc1-psx-26 -G0 -O2 -funsigned-char -fpeephole -ffunction-cse -fpcc-struct-return -fcommon -fverbose-asm -msoft-float -o "${{INPUT%.c}}.s" "${{INPUT%.c}}.i"

# Assemble
mipsel-linux-gnu-as -march=r3000 -O1 -G0 -o "$OUTPUT" "${{INPUT%.c}}.s"

# Clean up intermediates
rm -f "${{INPUT%.c}}.i" "${{INPUT%.c}}.s"

echo "$OUTPUT"
"""

    with open(compile_sh, 'w') as f:
        f.write(script_content)

    os.chmod(compile_sh, 0o755)
    return compile_sh


def check_permuter_installed() -> Tuple[bool, str]:
    """Check if decomp-permuter is installed and return the command."""
    # Check for pip-installed permuter
    try:
        result = subprocess.run(["permuter", "--help"], capture_output=True)
        if result.returncode == 0:
            return True, "permuter"
    except FileNotFoundError:
        pass

    # Check for the pinned setup clone
    local_permuter = ROOT_DIR / "build" / "decomp-permuter" / "permuter.py"
    if local_permuter.exists():
        return True, f"{sys.executable} {local_permuter}"

    # Check in venv
    venv_permuter = ROOT_DIR / ".venv" / "bin" / "permuter"
    if venv_permuter.exists():
        return True, str(venv_permuter)

    return False, ""


def setup_permuter_env(func_name: str, func_info: Dict, decomp_func: Dict) -> Path:
    """
    Set up the permuter environment for a function.

    Creates:
    - permuter_dir/func_name/
    - permuter_dir/func_name/base.c
    - permuter_dir/func_name/target.o
    - permuter_dir/func_name/compile.sh
    """
    vram_start = int(func_info['vram_start'], 16)
    size = func_info['size']
    source_file = decomp_func['source_file']

    # Create permuter directory
    func_dir = PERMUTER_DIR / func_name
    func_dir.mkdir(parents=True, exist_ok=True)

    print(f"Setting up permuter environment in {func_dir}")
    print()

    # Extract original bytes and create target.o
    print("Creating target.o from original binary...")
    original_bytes = extract_original_bytes(vram_start, size)
    create_target_object(func_name, vram_start, original_bytes, func_dir)

    # Read source and create base.c
    print("Creating base.c from source...")
    source_content = get_source_content(source_file)
    create_base_c(func_name, source_content, func_dir)

    # Create compile script
    print("Creating compile.sh...")
    create_compile_script(func_dir)

    print()
    print(f"Permuter environment ready at: {func_dir}")

    return func_dir


def run_permuter(func_dir: Path, func_name: str, iterations: int = 1000,
                 verbose: bool = False) -> Optional[str]:
    """
    Run the decomp-permuter on the function.

    Returns the matching code if found, None otherwise.
    """
    installed, permuter_cmd = check_permuter_installed()

    if not installed:
        print("=" * 60)
        print("ERROR: decomp-permuter not installed!")
        print("=" * 60)
        print()
        print("Install with one of these methods:")
        print()
        print("1. make setup-permuter")
        print("   OR")
        print("2. or install the upstream package: pip install decomp-permuter")
        print()
        print("After installing, run this command again.")
        return None

    print("=" * 60)
    print(f"Running decomp-permuter for {func_name}")
    print("=" * 60)
    print()
    print(f"Iterations: {iterations}")
    print(f"Permuter command: {permuter_cmd}")
    print()

    # Build permuter command
    cmd_parts = permuter_cmd.split()
    cmd = cmd_parts + [
        str(func_dir),
        "-j", "4",  # Use 4 threads
        "--iterations", str(iterations),
    ]

    if verbose:
        cmd.append("--debug")

    print(f"Running: {' '.join(cmd)}")
    print()
    print("-" * 60)

    try:
        # Run permuter
        result = subprocess.run(
            cmd,
            cwd=func_dir,
            capture_output=not verbose,
            text=True
        )

        if verbose:
            print(result.stdout)
            print(result.stderr)

        # Check for success
        # The permuter creates an "output" directory with successful permutations
        output_dir = func_dir / "output"
        if output_dir.exists():
            outputs = list(output_dir.glob("*.c"))
            if outputs:
                print()
                print("=" * 60)
                print("  MATCH FOUND!")
                print("=" * 60)
                print()
                print(f"Found {len(outputs)} matching variant(s)")

                # Read the best match
                best_match = outputs[0]
                with open(best_match, 'r') as f:
                    return f.read()

        print()
        print("-" * 60)
        print("No perfect match found in this run.")
        print()
        print("Suggestions:")
        print("- Increase iterations: --iterations 10000")
        print("- Check if the function needs manual adjustments")
        print("- See docs/MATCHING-PATTERNS.md for common patterns")

        return None

    except subprocess.CalledProcessError as e:
        print(f"Permuter failed: {e}")
        return None


def save_match_to_source(func_name: str, source_file: str, match_code: str):
    """Save the matching code back to the source file."""
    source_path = ROOT_DIR / source_file

    # Create backup
    backup_path = source_path.with_suffix('.c.bak')
    shutil.copy(source_path, backup_path)
    print(f"Backup saved to: {backup_path}")

    # Write new code
    with open(source_path, 'w') as f:
        f.write(match_code)

    print(f"Match saved to: {source_path}")

    # Update decompiled_functions.json status
    config = load_decomp_config()
    for func in config['functions']:
        if func['name'] == func_name:
            func['status'] = 'level3'
            func['notes'] = 'Byte-perfect match found by decomp-permuter'
            break

    with open(DECOMP_CONFIG, 'w') as f:
        json.dump(config, f, indent=4)

    print(f"Updated status to level3 in {DECOMP_CONFIG}")


def main():
    parser = argparse.ArgumentParser(
        description="Run decomp-permuter to find byte-perfect matches",
        epilog="""
Examples:
    python3 tools/permute_function.py func_8004B338
    python3 tools/permute_function.py func_8004B338 --iterations 10000
    python3 tools/permute_function.py func_8004B338 --save-match
    python3 tools/permute_function.py func_8004B338 --show-base --setup-only

Prerequisites:
    Install decomp-permuter:
        make setup-permuter
        """,
        formatter_class=argparse.RawDescriptionHelpFormatter
    )

    parser.add_argument(
        'function',
        help='Function name to permute (e.g., func_8004B338)'
    )
    parser.add_argument(
        '-i', '--iterations',
        type=int,
        default=1000,
        help='Number of permutation iterations (default: 1000)'
    )
    parser.add_argument(
        '-v', '--verbose',
        action='store_true',
        help='Show detailed permuter output'
    )
    parser.add_argument(
        '--save-match',
        action='store_true',
        help='Automatically save matching code to source file'
    )
    parser.add_argument(
        '--show-base',
        action='store_true',
        help='Show the base.c content that will be permuted'
    )
    parser.add_argument(
        '--setup-only',
        action='store_true',
        help='Only set up permuter environment, do not run'
    )
    parser.add_argument(
        '--clean',
        action='store_true',
        help='Clean existing permuter files and start fresh'
    )

    args = parser.parse_args()

    func_name = args.function

    # Load configs
    function_map = load_function_map()
    decomp_config = load_decomp_config()

    # Get function info
    func_info = get_function_info(func_name, function_map)
    if not func_info:
        print(f"Error: Function '{func_name}' not found in function map")
        sys.exit(1)

    # Get decompiled function info
    decomp_func = None
    for func in decomp_config.get('functions', []):
        if func['name'] == func_name:
            decomp_func = func
            break

    if not decomp_func:
        print(f"Error: Function '{func_name}' not in decompiled_functions.json")
        print("Add it to config/decompiled_functions.json first.")
        sys.exit(1)

    print("=" * 80)
    print(f"DECOMP-PERMUTER: {func_name}")
    print("=" * 80)
    print()
    print(f"Function:    {func_name}")
    print(f"VRAM:        {func_info['vram_start']}")
    print(f"Size:        {func_info['size']} bytes")
    print(f"Source:      {decomp_func['source_file']}")
    print(f"Status:      {decomp_func.get('status', 'unknown')}")
    print()

    # Clean if requested
    func_dir = PERMUTER_DIR / func_name
    if args.clean and func_dir.exists():
        print(f"Cleaning {func_dir}...")
        shutil.rmtree(func_dir)
        print()

    # Setup environment
    func_dir = setup_permuter_env(func_name, func_info, decomp_func)
    print()

    # Show base.c if requested
    if args.show_base:
        base_c = func_dir / "base.c"
        print("=" * 60)
        print("BASE.C CONTENT:")
        print("=" * 60)
        with open(base_c, 'r') as f:
            print(f.read())
        print("=" * 60)
        print()

    if args.setup_only:
        print("Setup complete. Run without --setup-only to start permuting.")
        print()
        print("Manual permuter usage:")
        print(f"  cd {func_dir}")
        print(f"  permuter .")
        sys.exit(0)

    # Run permuter
    match_code = run_permuter(func_dir, func_name, args.iterations, args.verbose)

    if match_code:
        print()
        print("=" * 60)
        print("MATCHING CODE:")
        print("=" * 60)
        print(match_code)
        print("=" * 60)

        if args.save_match:
            save_match_to_source(func_name, decomp_func['source_file'], match_code)
            print()
            print("Match has been saved!")
        else:
            print()
            print("To save this match, run with --save-match flag")

        sys.exit(0)
    else:
        sys.exit(1)


if __name__ == "__main__":
    main()
