#!/usr/bin/env python3
"""emit_psyq_asm_only.py -- write byte-exact asm_only listings for the Sony
Psy-Q LIBGTE functions Konami linked verbatim.

The retail bytes of these functions ARE shipped Sony objects (see
config/psyq_lib_symbols.json and docs/reference/PSYQ-LIB-IDENTIFICATION.md), so
there is nothing to decompile: the terminal state is asm_only.  This tool emits
one listing per symbol from disks/SLPS_000.65.

asm/main/matched/*.s is .gitignored, so these listings are a LOCAL artefact.
That is why this generator is tracked and the symbol table it reads is tracked:
the state is reproducible from the repo plus a legal disc image with

    python3 tools/analysis/emit_psyq_asm_only.py

Every instruction is emitted as `.word 0x........` with the disassembly in a
trailing comment.  That is deliberate: it is byte-exact by construction, it
reassembles without reconstructing branch labels, and it does not depend on
capstone's operand syntax agreeing with GNU as -- which matters here because
much of this code is COP2 (lwc2/swc2/cop2) that no assembler pass in this
project needs to re-encode.

    --only NAME   emit just one symbol
    --list        print what would be written, write nothing
"""
import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SYMS = os.path.join(ROOT, 'config', 'psyq_lib_symbols.json')
BIN = os.path.join(ROOT, 'disks', 'SLPS_000.65')
OUT = os.path.join(ROOT, 'asm', 'main', 'matched')

# Every verbatim Sony symbol here is asm_only, INCLUDING the ones with no COP2.
# RotMatrix (0x800A4710) was the one that looked like a C candidate -- 0 COP2
# words in 164 instructions, building its matrix in the integer unit off
# rcossin_tbl.  It is not.  Of its 35 nops, 1 fills a delay slot and 27 cover a
# mult/load hazard, but 6 sit immediately after an `sra rX,rY,12` that no
# hazard follows: the fixed-point multiply is a hand-written macro that always
# lays down `multu; nop; nop; mflo; sra; nop`.  No compiler emits a dead nop.
# Measured on top of that: Psy-Q GCC 2.6.0 -O2 on the natural C gives 91+29
# instructions in two functions against a single 164-instruction body.
NOT_ASM_ONLY = set()
TEXT_SECTION_START = 0x80041000
FILE_OFFSET_BASE = 0x800


def disasm(md, word, addr):
    if md is None:
        return None
    for ins in md.disasm(word.to_bytes(4, 'little'), addr):
        op = (' ' + ins.op_str) if ins.op_str else ''
        return (ins.mnemonic + op).strip()
    return None


def emit(sym, members, data, md):
    a, n = int(sym['address'], 16), sym['size']
    off = (a - TEXT_SECTION_START) + FILE_OFFSET_BASE
    body = data[off:off + n]
    if len(body) != n:
        raise SystemExit('short read for %s' % sym['name'])
    m = members[(sym['sdk'], sym['archive'], sym['member'])]
    cop2 = sym['cop2_words']
    L = ['.set noreorder', '.set noat', '', '.text', '.globl %s' % sym['name'],
         '', '/*', ' * %s' % sym['name'],
         ' * Address: %s' % sym['address'],
         ' * Size: %d bytes (%d instructions)' % (n, n // 4),
         ' * Region: Library (0x80086000-0x800BFFFF)',
         ' * Status: asm_only (byte-perfect ASM, no C)',
         ' *',
         ' * Provenance: Sony Psy-Q %s member %s (SDK %s), byte-verified by'
         % (sym['archive'], sym['member'], sym['sdk']),
         ' * WHOLE-MEMBER alignment: the member occupies %s..%s,'
         % (m['start'], m['end']),
         ' * %d words, %d of them compared at all 32 bits (the rest are covered'
         % (m['words'], m['full_words_compared']),
         ' * by the member\'s own relocation table), 0 mismatches.',
         ' *',
         ' * BLOCKER: sony_libgte_verbatim -- this is not Konami code.  %d of the'
         % cop2,
         ' * %d words are COP2 (lwc2/swc2/cop2), which C89 without GCC inline-asm'
         % (n // 4),
         ' * extensions cannot emit, and reproducing a shipped Sony object would',
         ' * need Sony\'s own build of LIBGTE rather than a decompilation of this',
         ' * game.  Filed in config/c_unmatchable.txt.',
         ' *',
         ' * Generated by tools/analysis/emit_psyq_asm_only.py from',
         ' * config/psyq_lib_symbols.json + disks/SLPS_000.65.  Every word is a',
         ' * .word so the listing is byte-exact by construction.',
         ' */',
         '%s:' % sym['name']]
    for i in range(0, n, 4):
        w = int.from_bytes(body[i:i + 4], 'little')
        d = disasm(md, w, a + i)
        L.append('    .word 0x%08X%s' % (w, ('    /* %s */' % d) if d else ''))
    L.append('')
    return '\n'.join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--only')
    ap.add_argument('--list', action='store_true')
    ap.add_argument('--force', action='store_true',
                    help='overwrite listings that already exist.  Off by '
                         'default: someone else may have written a listing '
                         'for the same symbol in a different style, and '
                         'clobbering it destroys work no git checkout can '
                         'restore (asm/main/matched/*.s is .gitignored).')
    args = ap.parse_args()
    print('ROOT = %s' % ROOT)
    d = json.load(open(SYMS))
    members = {(m['sdk'], m['archive'], m['member']): m for m in d['members']}
    data = open(BIN, 'rb').read()
    try:
        import capstone
        md = capstone.Cs(capstone.CS_ARCH_MIPS,
                         capstone.CS_MODE_MIPS32 | capstone.CS_MODE_LITTLE_ENDIAN)
    except Exception:
        md = None
        print('capstone unavailable: emitting .word only, no comments')
    os.makedirs(OUT, exist_ok=True)
    n = 0
    for sym in d['symbols']:
        if args.only and sym['name'] != args.only:
            continue
        if sym['name'] in NOT_ASM_ONLY:
            print('skip (not asm_only): %s' % sym['name'])
            continue
        path = os.path.join(OUT, sym['name'] + '.s')
        if os.path.exists(path) and not args.force and not args.list:
            print('skip (exists): %s' % path)
            continue
        if args.list:
            print('%-26s %s %5d -> %s' % (sym['name'], sym['address'],
                                          sym['size'], path))
            continue
        open(path, 'w').write(emit(sym, members, data, md))
        n += 1
    if not args.list:
        print('wrote %d listings to %s' % (n, OUT))
    return 0


if __name__ == '__main__':
    sys.exit(main())
