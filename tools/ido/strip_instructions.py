#!/usr/bin/env python3
"""
Strip specific instructions from .text section of a MIPS ELF object file.

Two modes:
  --remove OFFSETS: Remove instructions at given offsets (shrinks .text)
  --nop OFFSETS:    Replace instructions with NOP (no size change)

When removing, all subsequent code shifts back. Relocations and symbols are
adjusted. Branch targets are NOT adjusted (caller must ensure removed
instructions are before all branch/target pairs, or adjust manually).

For arg home saves (sw a0/a2 to stack) generated by IDO for 4+ param
functions, the saves are in the prologue before any branches, so removal
is safe without branch adjustment.

USAGE:
  # Remove sw a0 at 0x14, NOP sw a2 at 0x1c (delay slot):
  python3 strip_instructions.py input.o output.o --remove 0x14 --nop 0x1c

  # Remove multiple instructions:
  python3 strip_instructions.py input.o output.o --remove 0x14,0x20

  # Verbose mode:
  python3 strip_instructions.py input.o output.o --remove 0x14 -v
"""

import sys
import struct
import argparse


def parse_offsets(s):
    """Parse comma-separated hex/decimal offsets."""
    if not s:
        return []
    offsets = []
    for part in s.split(','):
        part = part.strip()
        if part.startswith('0x') or part.startswith('0X'):
            offsets.append(int(part, 16))
        else:
            offsets.append(int(part))
    return offsets


def parse_elf_sections(elf_data):
    """Parse ELF and return section info dict."""
    if elf_data[:4] != b'\x7fELF':
        raise ValueError("Not an ELF file")

    endian = '<'  # Assume little-endian (PS1)

    e_shoff = struct.unpack(endian + 'I', elf_data[32:36])[0]
    e_shentsize = struct.unpack(endian + 'H', elf_data[46:48])[0]
    e_shnum = struct.unpack(endian + 'H', elf_data[48:50])[0]
    e_shstrndx = struct.unpack(endian + 'H', elf_data[50:52])[0]

    shstrtab_off = e_shoff + e_shstrndx * e_shentsize
    shstrtab_addr = struct.unpack(endian + 'I',
                                  elf_data[shstrtab_off+16:shstrtab_off+20])[0]
    shstrtab_size = struct.unpack(endian + 'I',
                                  elf_data[shstrtab_off+20:shstrtab_off+24])[0]
    shstrtab = elf_data[shstrtab_addr:shstrtab_addr+shstrtab_size]

    sections = {}
    for i in range(e_shnum):
        sh_off = e_shoff + i * e_shentsize
        sh_name_idx = struct.unpack(endian + 'I', elf_data[sh_off:sh_off+4])[0]
        sh_offset = struct.unpack(endian + 'I', elf_data[sh_off+16:sh_off+20])[0]
        sh_size = struct.unpack(endian + 'I', elf_data[sh_off+20:sh_off+24])[0]

        name_end = shstrtab.find(b'\x00', sh_name_idx)
        name = shstrtab[sh_name_idx:name_end].decode('ascii')

        sections[name] = {
            'index': i,
            'header_off': sh_off,
            'offset': sh_offset,
            'size': sh_size,
        }

    return sections


def strip_instructions(elf_data, remove_offsets, nop_offsets, verbose=False):
    """Strip or NOP specific instructions in .text.

    Args:
        elf_data: Raw ELF file bytes
        remove_offsets: List of .text offsets to remove (shrinks .text)
        nop_offsets: List of .text offsets to replace with NOP
        verbose: Print details

    Returns:
        (patched_data, remove_count, nop_count)
    """
    patched = bytearray(elf_data)
    endian = '<'

    sections = parse_elf_sections(elf_data)

    if '.text' not in sections:
        raise ValueError(".text section not found")

    text = sections['.text']
    text_offset = text['offset']
    text_size = text['size']
    text_idx = text['index']

    # Validate offsets
    for off in remove_offsets + nop_offsets:
        if off < 0 or off >= text_size:
            raise ValueError(
                f"Offset 0x{off:x} out of range (text size 0x{text_size:x})")
        if off % 4 != 0:
            raise ValueError(f"Offset 0x{off:x} not 4-byte aligned")

    # Step 1: Apply NOPs (no size change, do first)
    for off in nop_offsets:
        file_off = text_offset + off
        old_word = struct.unpack(endian + 'I',
                                 patched[file_off:file_off+4])[0]
        struct.pack_into(endian + 'I', patched, file_off, 0x00000000)
        if verbose:
            print(f"  NOP at .text+0x{off:04x}: was 0x{old_word:08x}")

    # Step 2: Remove instructions (sort descending so shifts don't cascade)
    sorted_removes = sorted(remove_offsets, reverse=True)

    for off in sorted_removes:
        file_off = text_offset + off
        old_word = struct.unpack(endian + 'I',
                                 patched[file_off:file_off+4])[0]
        if verbose:
            print(f"  REMOVE at .text+0x{off:04x}: was 0x{old_word:08x}")

        # Remove 4 bytes from .text at this position
        remaining = patched[file_off + 4:text_offset + text_size]
        patched[file_off:file_off + len(remaining)] = remaining
        # Zero-pad the freed space at the end
        pad_start = text_offset + text_size - 4
        patched[pad_start:pad_start + 4] = b'\x00\x00\x00\x00'

        # Adjust relocations
        if '.rel.text' in sections:
            rel = sections['.rel.text']
            rel_off = rel['offset']
            rel_size = rel['size']
            num_relocs = rel_size // 8
            new_relocs = bytearray()

            for i in range(num_relocs):
                ent_off = rel_off + i * 8
                r_offset = struct.unpack(endian + 'I',
                                         patched[ent_off:ent_off+4])[0]
                r_info = struct.unpack(endian + 'I',
                                       patched[ent_off+4:ent_off+8])[0]

                if r_offset == off:
                    # Relocation at removed instruction — skip
                    if verbose:
                        print(f"    Dropping reloc at 0x{r_offset:x}")
                    continue
                elif r_offset > off:
                    r_offset -= 4
                    if verbose:
                        print(f"    Reloc shifted: 0x{r_offset+4:x} -> "
                              f"0x{r_offset:x}")

                new_relocs.extend(struct.pack(endian + 'I', r_offset))
                new_relocs.extend(struct.pack(endian + 'I', r_info))

            # Write back, pad
            new_rel_size = len(new_relocs)
            padded = new_relocs + b'\x00' * (rel_size - new_rel_size)
            patched[rel_off:rel_off + rel_size] = padded

            # Update .rel.text size
            struct.pack_into(endian + 'I', patched,
                             rel['header_off'] + 20, new_rel_size)
            # Update our tracking
            sections['.rel.text']['size'] = new_rel_size

        # Update .text size
        text_size -= 4
        struct.pack_into(endian + 'I', patched,
                         text['header_off'] + 20, text_size)

        # Adjust symbols
        if '.symtab' in sections:
            sym = sections['.symtab']
            num_syms = sym['size'] // 16
            for i in range(num_syms):
                sym_off = sym['offset'] + i * 16
                st_value = struct.unpack(endian + 'I',
                                         patched[sym_off+4:sym_off+8])[0]
                st_size = struct.unpack(endian + 'I',
                                        patched[sym_off+8:sym_off+12])[0]
                st_shndx = struct.unpack(endian + 'H',
                                          patched[sym_off+14:sym_off+16])[0]

                if st_shndx != text_idx:
                    continue

                new_value = st_value
                new_size = st_size

                if st_value > off:
                    new_value = st_value - 4
                if st_size > 0 and st_value <= off < st_value + st_size:
                    new_size = st_size - 4

                if new_value != st_value or new_size != st_size:
                    struct.pack_into(endian + 'I', patched,
                                     sym_off + 4, new_value)
                    struct.pack_into(endian + 'I', patched,
                                     sym_off + 8, new_size)

        # Adjust nop_offsets that are after this removal
        nop_offsets = [n - 4 if n > off else n for n in nop_offsets]

    return bytes(patched), len(remove_offsets), len(nop_offsets)


def main():
    parser = argparse.ArgumentParser(
        description='Strip specific instructions from .text section',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
EXAMPLES:
  # Remove arg home save at 0x14, NOP delay-slot save at 0x1c:
  %(prog)s input.o output.o --remove 0x14 --nop 0x1c

  # Remove multiple instructions:
  %(prog)s input.o output.o --remove 0x14,0x20

NOTES:
  Branch targets are NOT adjusted. Only use --remove for instructions
  that are before all branch/target pairs (e.g., prologue arg saves).
  Use --nop for instructions in delay slots.
        """)

    parser.add_argument('input', help='Input ELF object file')
    parser.add_argument('output', help='Output patched file')
    parser.add_argument('--remove', type=str, default='',
                        help='Comma-separated offsets to remove (shrinks .text)')
    parser.add_argument('--nop', type=str, default='',
                        help='Comma-separated offsets to NOP out')
    parser.add_argument('-v', '--verbose', action='store_true',
                        help='Print detailed changes')

    args = parser.parse_args()

    remove_offsets = parse_offsets(args.remove)
    nop_offsets = parse_offsets(args.nop)

    if not remove_offsets and not nop_offsets:
        parser.error("Must specify --remove and/or --nop offsets")

    with open(args.input, 'rb') as f:
        elf_data = f.read()

    patched, removed, nopped = strip_instructions(
        elf_data, remove_offsets, nop_offsets, verbose=args.verbose)

    with open(args.output, 'wb') as f:
        f.write(patched)

    print(f"Removed {removed} instructions ({removed * 4} bytes), "
          f"NOPped {nopped} instructions")


if __name__ == '__main__':
    sys.exit(main() or 0)
