#!/usr/bin/env python3
"""
Fix assembly files for PS1 compatibility.

Converts MIPS III/IV instructions to MIPS I equivalents for R3000 CPU.
Handles instruction fixes generated by splat or other disassemblers.
"""

import argparse
import os
import re
import sys
from pathlib import Path


# MIPS III/IV instructions that need to be converted for MIPS I
INSTRUCTION_FIXES = {
    # MIPS III instructions not available on R3000
    'daddiu': 'addiu',  # Use 32-bit version
    'daddu': 'addu',
    'dsub': 'sub',
    'dsubu': 'subu',
    'dmult': 'mult',
    'dmultu': 'multu',
    'ddiv': 'div',
    'ddivu': 'divu',
    'dsll': 'sll',
    'dsrl': 'srl',
    'dsra': 'sra',
    'dsllv': 'sllv',
    'dsrlv': 'srlv',
    'dsrav': 'srav',
    'ld': 'lw',  # 64-bit load -> 32-bit (may need adjustment)
    'sd': 'sw',  # 64-bit store -> 32-bit

    # Conditional moves (MIPS IV)
    'movz': None,  # Need manual conversion
    'movn': None,

    # MIPS II instructions sometimes not supported by old assemblers
    'sync': 'nop',  # Memory barrier -> NOP on R3000
}

# Patterns for register fixes
REGISTER_PATTERNS = [
    # Fix $fcc0 references (no FPU condition codes on R3000)
    (r'\$fcc\d+', '$0'),
]


def fix_instruction_line(line: str) -> str:
    """Fix a single assembly line for MIPS I compatibility."""

    # Skip empty lines and comments
    stripped = line.strip()
    if not stripped or stripped.startswith('#') or stripped.startswith('/*'):
        return line

    # Check for instruction fixes
    for old_insn, new_insn in INSTRUCTION_FIXES.items():
        # Match instruction at start of line (after optional whitespace/label)
        pattern = rf'(\s+){old_insn}(\s+)'
        if re.search(pattern, line, re.IGNORECASE):
            if new_insn is None:
                # Can't auto-convert, add warning comment
                line = f"/* WARNING: {old_insn} not available on R3000 */\n{line}"
            else:
                line = re.sub(pattern, rf'\1{new_insn}\2', line, flags=re.IGNORECASE)

    # Apply register pattern fixes
    for pattern, replacement in REGISTER_PATTERNS:
        line = re.sub(pattern, replacement, line)

    return line


def fix_assembly_file(filepath: Path, dry_run: bool = False) -> int:
    """Fix a single assembly file. Returns number of changes made."""

    with open(filepath, 'r') as f:
        original_lines = f.readlines()

    fixed_lines = []
    changes = 0

    for line in original_lines:
        fixed = fix_instruction_line(line)
        if fixed != line:
            changes += 1
        fixed_lines.append(fixed)

    if changes > 0 and not dry_run:
        with open(filepath, 'w') as f:
            f.writelines(fixed_lines)

    return changes


def main():
    parser = argparse.ArgumentParser(
        description='Fix assembly files for PS1 (MIPS I) compatibility'
    )
    parser.add_argument('path', help='Directory or file to process')
    parser.add_argument('--dry-run', action='store_true',
                        help='Show what would be changed without modifying files')
    parser.add_argument('-v', '--verbose', action='store_true',
                        help='Verbose output')

    args = parser.parse_args()

    path = Path(args.path)

    if path.is_file():
        files = [path]
    elif path.is_dir():
        files = list(path.glob('**/*.s'))
    else:
        print(f"ERROR: Path not found: {path}")
        sys.exit(1)

    total_changes = 0
    files_modified = 0

    for filepath in files:
        changes = fix_assembly_file(filepath, args.dry_run)
        if changes > 0:
            files_modified += 1
            total_changes += changes
            if args.verbose:
                action = "Would modify" if args.dry_run else "Modified"
                print(f"{action}: {filepath} ({changes} changes)")

    print(f"\n{'Would modify' if args.dry_run else 'Modified'} {files_modified} files, {total_changes} total changes")


if __name__ == '__main__':
    main()
