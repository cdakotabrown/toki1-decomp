#!/usr/bin/env python3
"""
Generate pure .word assembly for the Tokimeki Memorial executable.

This produces a single assembly file that uses ONLY .word directives,
guaranteeing byte-perfect reproduction. This is the safest approach
when dealing with embedded data and unusual code patterns.

Usage:
    python3 tools/generate_word_asm.py --exe disks/SLPS_000.65 --output asm/jp/main/main.s
"""

import argparse
import struct
from pathlib import Path


def generate_word_assembly(exe_path: str, output_path: str, verbose: bool = False):
    """Generate pure .word assembly from the executable."""

    with open(exe_path, 'rb') as f:
        data = f.read()

    # Parse PS-X EXE header
    def read_u32(offset):
        return struct.unpack('<I', data[offset:offset+4])[0]

    text_file_start = read_u32(0x08)  # 0x800
    text_size = read_u32(0x0C)
    text_vram_start = read_u32(0x18)

    text_file_end = text_file_start + text_size
    file_size = len(data)

    print(f"Executable: {exe_path}")
    print(f"Header: 0x000 - 0x{text_file_start:X} ({text_file_start} bytes)")
    print(f"Text: 0x{text_file_start:X} - 0x{text_file_end:X} ({text_size} bytes)")
    print(f"Data: 0x{text_file_end:X} - 0x{file_size:X} ({file_size - text_file_end} bytes)")
    print(f"VRAM: 0x{text_vram_start:08X}")
    print()

    Path(output_path).parent.mkdir(parents=True, exist_ok=True)

    with open(output_path, 'w') as f:
        # Header comment
        f.write("# Tokimeki Memorial (SLPS-00065) - Pure .word assembly\n")
        f.write("# Generated by generate_word_asm.py\n")
        f.write("# This file uses ONLY .word directives for byte-perfect reproduction\n")
        f.write("#\n")
        f.write(f"# Header: 0x000 - 0x{text_file_start:X}\n")
        f.write(f"# Text:   0x{text_file_start:X} - 0x{text_file_end:X} (VRAM 0x{text_vram_start:08X})\n")
        f.write(f"# Data:   0x{text_file_end:X} - 0x{file_size:X}\n")
        f.write("\n")

        # Header section (include as raw bytes)
        f.write(".section .header, \"a\"\n")
        f.write("# PS-X EXE Header (2048 bytes)\n")
        for i in range(0, text_file_start, 4):
            word = struct.unpack('<I', data[i:i+4])[0]
            f.write(f"    .word 0x{word:08X}\n")
        f.write("\n")

        # Text section
        f.write(".section .text\n")
        f.write(f".set noreorder\n")
        f.write(f".set noat\n")
        f.write(f"\n")
        f.write(f"# Text section start: VRAM 0x{text_vram_start:08X}\n")
        f.write(f".globl main_text_start\n")
        f.write(f"main_text_start:\n")

        words_written = 0
        for i in range(text_file_start, text_file_end, 4):
            word = struct.unpack('<I', data[i:i+4])[0]
            vram = text_vram_start + (i - text_file_start)

            # Add comments every 256 bytes for navigation
            if (i - text_file_start) % 256 == 0:
                f.write(f"\n# === VRAM 0x{vram:08X} (file 0x{i:X}) ===\n")

            f.write(f"    .word 0x{word:08X}  # 0x{vram:08X}\n")
            words_written += 1

            if verbose and words_written % 10000 == 0:
                print(f"  Written {words_written} words...")

        f.write(f"\n")
        f.write(f".globl main_text_end\n")
        f.write(f"main_text_end:\n")
        f.write(f"\n")

        # Data section
        f.write(".section .data\n")
        f.write(f"# Data section start: VRAM 0x{text_vram_start + text_size:08X}\n")
        f.write(f".globl main_data_start\n")
        f.write(f"main_data_start:\n")

        for i in range(text_file_end, file_size, 4):
            word = struct.unpack('<I', data[i:i+4])[0]
            vram = text_vram_start + (i - text_file_start)

            # Add comments every 256 bytes for navigation
            if (i - text_file_end) % 256 == 0:
                f.write(f"\n# === VRAM 0x{vram:08X} (file 0x{i:X}) ===\n")

            f.write(f"    .word 0x{word:08X}  # 0x{vram:08X}\n")
            words_written += 1

        f.write(f"\n")
        f.write(f".globl main_data_end\n")
        f.write(f"main_data_end:\n")

    print(f"Generated {output_path}")
    print(f"Total words: {words_written}")


def main():
    parser = argparse.ArgumentParser(description='Generate pure .word assembly')
    parser.add_argument('--exe', default='disks/SLPS_000.65', help='Input executable')
    parser.add_argument('--output', default='asm/jp/main/main.s', help='Output assembly file')
    parser.add_argument('--verbose', '-v', action='store_true', help='Verbose output')

    args = parser.parse_args()
    generate_word_assembly(args.exe, args.output, args.verbose)


if __name__ == '__main__':
    main()
