#!/usr/bin/env python3
"""
Build byte-perfect binary from raw executable bytes.

This tool generates:
1. A .word-based assembly file from the original executable
2. A linker script for the PS1 memory layout
3. Assembles and links to produce an identical binary

Usage:
    python3 build_from_bytes.py --exe disks/SLPS_000.65 --asm build/jp/raw/main.s \
        --ld build/jp/raw/main.ld --elf build/jp/raw/main.elf --bin build/jp/raw/SLPS_000.65.new
"""

import argparse
import os
import struct
import subprocess
import sys
from pathlib import Path


# PS1 executable header constants
PS_X_EXE_MAGIC = b"PS-X EXE"
HEADER_SIZE = 2048  # PS1 EXE header is 2048 bytes


def parse_psx_header(data: bytes) -> dict:
    """Parse PS1 executable header and return metadata."""
    if data[:8] != PS_X_EXE_MAGIC:
        raise ValueError(f"Invalid PS1 executable: expected magic '{PS_X_EXE_MAGIC.decode()}', got '{data[:8]}'")

    # PS-X EXE header format (little-endian):
    # 0x00-0x07: "PS-X EXE" magic
    # 0x08-0x0F: Zerofilled
    # 0x10-0x13: Initial PC (entry point)
    # 0x14-0x17: Initial GP (global pointer)
    # 0x18-0x1B: Destination address in RAM
    # 0x1C-0x1F: File size (excluding header)
    # 0x20-0x23: Data section start
    # 0x24-0x27: Data section size
    # 0x28-0x2B: BSS section start
    # 0x2C-0x2F: BSS section size
    # 0x30-0x33: Initial SP base
    # 0x34-0x37: Initial SP offset

    header = {
        'magic': data[:8].decode('ascii'),
        'initial_pc': struct.unpack('<I', data[0x10:0x14])[0],
        'initial_gp': struct.unpack('<I', data[0x14:0x18])[0],
        'dest_addr': struct.unpack('<I', data[0x18:0x1C])[0],
        'file_size': struct.unpack('<I', data[0x1C:0x20])[0],
        'data_start': struct.unpack('<I', data[0x20:0x24])[0],
        'data_size': struct.unpack('<I', data[0x24:0x28])[0],
        'bss_start': struct.unpack('<I', data[0x28:0x2C])[0],
        'bss_size': struct.unpack('<I', data[0x2C:0x30])[0],
        'sp_base': struct.unpack('<I', data[0x30:0x34])[0],
        'sp_offset': struct.unpack('<I', data[0x34:0x38])[0],
    }

    return header


def generate_word_assembly(data: bytes, header: dict, output_path: Path) -> None:
    """Generate assembly file using .word directives for byte-perfect reproduction."""

    # Code section starts after header
    code_data = data[HEADER_SIZE:]

    with open(output_path, 'w') as f:
        f.write("/* Auto-generated byte-perfect assembly for SLPS-00065 */\n")
        f.write("/* DO NOT EDIT - regenerate with build_from_bytes.py */\n\n")

        f.write(".set noat\n")
        f.write(".set noreorder\n\n")

        # Header section (include the PS-X EXE header)
        f.write(".section .header, \"a\"\n")
        f.write(".balign 4\n")
        f.write("header_start:\n")

        header_data = data[:HEADER_SIZE]
        for i in range(0, len(header_data), 4):
            word = struct.unpack('<I', header_data[i:i+4])[0]
            f.write(f"    .word 0x{word:08X}\n")

        f.write("\n")

        # Code/data section
        f.write(".section .text, \"ax\"\n")
        f.write(".balign 4\n")
        f.write("code_start:\n")

        # Write code as .word directives (4 bytes at a time)
        for i in range(0, len(code_data), 4):
            if i + 4 <= len(code_data):
                word = struct.unpack('<I', code_data[i:i+4])[0]
                f.write(f"    .word 0x{word:08X}\n")
            else:
                # Handle trailing bytes
                for j in range(i, len(code_data)):
                    f.write(f"    .byte 0x{code_data[j]:02X}\n")

        f.write("\ncode_end:\n")

    print(f"Generated assembly: {output_path}")
    print(f"  Header size: {HEADER_SIZE} bytes")
    print(f"  Code size: {len(code_data)} bytes")
    print(f"  Load address: 0x{header['dest_addr']:08X}")
    print(f"  Entry point: 0x{header['initial_pc']:08X}")


def generate_linker_script(header: dict, output_path: Path) -> None:
    """Generate linker script for PS1 memory layout."""

    with open(output_path, 'w') as f:
        f.write("/* Auto-generated linker script for SLPS-00065 */\n")
        f.write("/* DO NOT EDIT - regenerate with build_from_bytes.py */\n\n")

        f.write("OUTPUT_FORMAT(\"elf32-tradlittlemips\")\n")
        f.write("OUTPUT_ARCH(mips)\n\n")

        f.write("MEMORY {\n")
        f.write("    rom (rx) : ORIGIN = 0x00000000, LENGTH = 2M\n")
        f.write("}\n\n")

        f.write("SECTIONS {\n")
        f.write("    .header 0x0 : {\n")
        f.write("        *(.header)\n")
        f.write("    } > rom\n\n")

        f.write(f"    .text 0x{header['dest_addr']:08X} : AT(0x800) {{\n")
        f.write("        *(.text)\n")
        f.write("        *(.text.*)\n")
        f.write("        *(.rodata)\n")
        f.write("        *(.rodata.*)\n")
        f.write("        *(.data)\n")
        f.write("        *(.data.*)\n")
        f.write("    } > rom\n\n")

        f.write("    /DISCARD/ : {\n")
        f.write("        *(.MIPS.abiflags)\n")
        f.write("        *(.reginfo)\n")
        f.write("        *(.pdr)\n")
        f.write("        *(.comment)\n")
        f.write("        *(.note*)\n")
        f.write("        *(.eh_frame*)\n")
        f.write("        *(.mdebug*)\n")
        f.write("    }\n")
        f.write("}\n")

    print(f"Generated linker script: {output_path}")


def assemble_and_link(asm_path: Path, ld_path: Path, elf_path: Path, bin_path: Path) -> bool:
    """Assemble the .s file and link to produce ELF and binary."""

    obj_path = asm_path.with_suffix('.o')

    # Assembler command
    as_cmd = [
        'mipsel-linux-gnu-as',
        '-march=r3000',
        '-mabi=32',
        '-o', str(obj_path),
        str(asm_path)
    ]

    print(f"Assembling: {' '.join(as_cmd)}")
    result = subprocess.run(as_cmd, capture_output=True, text=True)
    if result.returncode != 0:
        print(f"Assembly failed:\n{result.stderr}")
        return False

    # Linker command
    ld_cmd = [
        'mipsel-linux-gnu-ld',
        '-T', str(ld_path),
        '-o', str(elf_path),
        str(obj_path),
        '--noinhibit-exec'
    ]

    print(f"Linking: {' '.join(ld_cmd)}")
    result = subprocess.run(ld_cmd, capture_output=True, text=True)
    if result.returncode != 0:
        print(f"Linking failed:\n{result.stderr}")
        return False

    # Extract sections separately and concatenate
    header_bin = bin_path.with_suffix('.header.bin')
    text_bin = bin_path.with_suffix('.text.bin')

    # Extract .header section
    objcopy_header = [
        'mipsel-linux-gnu-objcopy',
        '-O', 'binary',
        '--only-section=.header',
        str(elf_path),
        str(header_bin)
    ]

    print(f"Extracting header: {' '.join(objcopy_header)}")
    result = subprocess.run(objcopy_header, capture_output=True, text=True)
    if result.returncode != 0:
        print(f"objcopy header failed:\n{result.stderr}")
        return False

    # Extract .text section
    objcopy_text = [
        'mipsel-linux-gnu-objcopy',
        '-O', 'binary',
        '--only-section=.text',
        str(elf_path),
        str(text_bin)
    ]

    print(f"Extracting text: {' '.join(objcopy_text)}")
    result = subprocess.run(objcopy_text, capture_output=True, text=True)
    if result.returncode != 0:
        print(f"objcopy text failed:\n{result.stderr}")
        return False

    # Concatenate header + text
    with open(bin_path, 'wb') as out:
        with open(header_bin, 'rb') as h:
            out.write(h.read())
        with open(text_bin, 'rb') as t:
            out.write(t.read())

    # Clean up temp files
    header_bin.unlink()
    text_bin.unlink()

    return True


def verify_binary(original_path: Path, rebuilt_path: Path) -> bool:
    """Verify the rebuilt binary matches the original."""

    with open(original_path, 'rb') as f:
        original = f.read()

    with open(rebuilt_path, 'rb') as f:
        rebuilt = f.read()

    if len(original) != len(rebuilt):
        print(f"Size mismatch: original={len(original)}, rebuilt={len(rebuilt)}")
        return False

    if original == rebuilt:
        print("SUCCESS: Binary matches original exactly!")
        return True
    else:
        # Find first difference
        for i, (a, b) in enumerate(zip(original, rebuilt)):
            if a != b:
                print(f"First difference at offset 0x{i:X}: original=0x{a:02X}, rebuilt=0x{b:02X}")
                break
        return False


def main():
    parser = argparse.ArgumentParser(
        description='Build byte-perfect binary from raw executable bytes'
    )
    parser.add_argument('--exe', required=True, help='Path to original PS1 executable')
    parser.add_argument('--asm', required=True, help='Output assembly file path')
    parser.add_argument('--ld', required=True, help='Output linker script path')
    parser.add_argument('--elf', required=True, help='Output ELF file path')
    parser.add_argument('--bin', required=True, help='Output binary file path')
    parser.add_argument('--no-build', action='store_true', help='Only generate files, do not assemble/link')

    args = parser.parse_args()

    exe_path = Path(args.exe)
    asm_path = Path(args.asm)
    ld_path = Path(args.ld)
    elf_path = Path(args.elf)
    bin_path = Path(args.bin)

    # Check original exists
    if not exe_path.exists():
        print(f"ERROR: Original executable not found: {exe_path}")
        print("")
        print("Please provide the original game executable (SLPS_000.65).")
        print("You can extract it from the game disc using:")
        print("  make extract-exe")
        print("")
        print("Or place the extracted executable in the disks/ directory.")
        sys.exit(1)

    # Create output directories
    asm_path.parent.mkdir(parents=True, exist_ok=True)
    ld_path.parent.mkdir(parents=True, exist_ok=True)
    elf_path.parent.mkdir(parents=True, exist_ok=True)
    bin_path.parent.mkdir(parents=True, exist_ok=True)

    # Read original executable
    print(f"Reading original executable: {exe_path}")
    with open(exe_path, 'rb') as f:
        data = f.read()

    print(f"  Size: {len(data)} bytes")

    # Parse header
    header = parse_psx_header(data)
    print(f"  Load address: 0x{header['dest_addr']:08X}")
    print(f"  Entry point: 0x{header['initial_pc']:08X}")
    print(f"  Code size: {header['file_size']} bytes")
    print("")

    # Generate assembly
    generate_word_assembly(data, header, asm_path)
    print("")

    # Generate linker script
    generate_linker_script(header, ld_path)
    print("")

    if args.no_build:
        print("Skipping assembly/linking (--no-build specified)")
        return 0

    # Assemble and link
    print("Building...")
    if not assemble_and_link(asm_path, ld_path, elf_path, bin_path):
        print("Build failed!")
        sys.exit(1)

    print("")
    print(f"Output binary: {bin_path}")
    print(f"  Size: {bin_path.stat().st_size} bytes")

    # Verify
    print("")
    print("Verifying...")
    if verify_binary(exe_path, bin_path):
        # Calculate SHA1
        import hashlib
        with open(bin_path, 'rb') as f:
            sha1 = hashlib.sha1(f.read()).hexdigest()
        print(f"SHA1: {sha1}")
        return 0
    else:
        print("VERIFICATION FAILED!")
        return 1


if __name__ == '__main__':
    sys.exit(main())
