#!/usr/bin/env python3
"""build_clean_main.py - Build the MAIN executable (SLPS_000.65) from SOURCE.

Replaces the whole-image ROM-byte
model of build_level3_c.py (original exe + patched C functions) with the same
source-priority model as the overlay clean build:

  * every REGISTERED byte-perfect C function (config/level3_functions.json,
    entries whose source is a .c) -> compiled with the existing level3
    pipeline (IDO/GCC + PostProc + fixup_relocations) and STRICTLY compared
    to the original window; a mismatch falls back to the as-path and is
    recorded as debt.
  * every other text byte -> assembled from LOCALLY-GENERATED disassembly
    (asm/main is gitignored; the .s chunks are generated into
    build/clean_main_asm/ with the same disassembler as the overlay orphan
    flow and then run through mipsel-linux-gnu-as at their VAs). Interleaved
    rodata/jump-tables inside these spans round-trip through the
    disassembler as pseudo-instructions/.word — byte-exact by construction,
    and verified per chunk.
  * the 0x800 PS-X EXE header (load-address metadata) is spliced from the
    original (metadata tier, reported in the debt file).
  * --allow-rom-fallback: if a chunk cannot be assembled byte-identically,
    splice ONLY those bytes from the original and record them LOUDLY as
    rom_fallback debt. Without the flag such a chunk fails the build.

Gate: whole-file SHA1 vs disks/SLPS_000.65 + first-divergence report.
Debt: recorded under key "main" in config/clean_build_debt.json
(build_clean_exn.py --report prints it).

Usage:
    python3 tools/build/build_clean_main.py --verify [-j N] [--no-cache]
    python3 tools/build/build_clean_main.py --verify --allow-rom-fallback

Output: build/SLPS_000.65.clean
"""
import concurrent.futures
import hashlib
import json
import os
import re
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).parent.parent.parent
sys.path.insert(0, str(ROOT / "tools" / "build"))
sys.path.insert(0, str(ROOT / "tools" / "overlay"))

from parse_postproc import (parse_postproc_header, parse_compile_flags,  # noqa
                            parse_compiler, parse_compile_env)
from build_level3_c import compile_c_function, fixup_relocations  # noqa
from build_clean_exn import assemble_at_va  # noqa
from extract_exn_functions import disassemble_function  # noqa

ORIGINAL = ROOT / "disks" / "SLPS_000.65"
LEVEL3 = ROOT / "config" / "level3_functions.json"
DEBT_FILE = ROOT / "config" / "clean_build_debt.json"
OUT = ROOT / "build" / "SLPS_000.65.clean"
ASM_DIR = ROOT / "build" / "clean_main_asm"      # locally generated, gitignored
CACHE_DIR = ROOT / "build" / "clean_exn_cache" / "MAIN"

TEXT_BASE = 0x80041000
FILE_BASE = 0x800
CHUNK = 0x4000  # max generated-.s chunk size (bytes)

# v2 invalidates failures cached by the old threaded relocation handoff.
CACHE_VERSION = "2"


def file_off(addr: int) -> int:
    return addr - TEXT_BASE + FILE_BASE


def sha1(b: bytes) -> str:
    return hashlib.sha1(b).hexdigest()


# ---------------------------------------------------------------------------
# as-path: locally generated disassembly chunks
# ---------------------------------------------------------------------------

def gen_chunk_s(exe: bytes, addr: int, size: int) -> Path:
    """Generate (or reuse) the local disassembly .s for [addr, addr+size)."""
    ASM_DIR.mkdir(parents=True, exist_ok=True)
    name = f"chunk_{addr:08X}_{size:X}"
    out = ASM_DIR / f"{name}.s"
    if out.exists():
        return out
    lines = [
        ".set noreorder", ".set noat", "", ".text",
        f".globl {name}", "",
        f"/* Chunk: {name} (locally generated by build_clean_main.py;",
        f" * NOT committed — asm/main stays gitignored per spec)",
        f" * Address: 0x{addr:08X}",
        f" * Size: {size} bytes ({size // 4} instructions)",
        " */",
        f"{name}:",
    ]
    body = disassemble_function(exe, file_off(addr), size,
                                TEXT_BASE - FILE_BASE)
    # Round-trip safety: these chunks contain interleaved DATA whose words
    # can decode to instruction forms that do not print every bit field
    # (mfhi drops rs/rt/sa, mult drops rd/sa, jr drops hint bits, teq drops
    # its code field, ...). Real code always has those fields zero; data
    # often doesn't. Emit the raw .word whenever the decode is not provably
    # lossless so assembly is an exact inverse.
    import struct as _struct
    safe = []
    for i, line in enumerate(body):
        w = _struct.unpack_from("<I", exe, file_off(addr) + i * 4)[0]
        if _decode_is_lossless(w):
            safe.append(line)
        else:
            safe.append(f"    .word   0x{w:08X}  # lossy decode")
    lines.extend(safe)
    out.write_text("\n".join(lines) + "\n")
    return out


def _decode_is_lossless(w: int) -> bool:
    """True iff the repo disassembler's text for `w` preserves every bit
    (i.e. the printed operand fields cover all variable bits and the
    remaining bits are zero, as they are in genuine code)."""
    if w == 0:
        return True  # nop
    op = (w >> 26) & 0x3F
    rs = (w >> 21) & 0x1F
    rt = (w >> 16) & 0x1F
    rd = (w >> 11) & 0x1F
    sa = (w >> 6) & 0x1F
    funct = w & 0x3F
    if op == 0x00:  # SPECIAL
        if funct in (0x20, 0x21, 0x22, 0x23, 0x24, 0x25, 0x26, 0x27,
                     0x2A, 0x2B):          # 3-reg R-type
            return sa == 0
        if funct in (0x00, 0x02, 0x03):    # immediate shifts
            return rs == 0
        if funct in (0x04, 0x06, 0x07):    # variable shifts
            return sa == 0
        if funct in (0x18, 0x19, 0x1A, 0x1B):  # mult/div
            return rd == 0 and sa == 0
        if funct in (0x10, 0x12):          # mfhi/mflo
            return rs == 0 and rt == 0 and sa == 0
        if funct in (0x11, 0x13):          # mthi/mtlo
            return rt == 0 and rd == 0 and sa == 0
        if funct == 0x08:                  # jr
            return rt == 0 and rd == 0 and sa == 0
        if funct == 0x09:                  # jalr (gas refuses rd == rs)
            return rt == 0 and sa == 0 and rd != rs
        if funct in (0x0C, 0x0D):          # syscall/break: full code printed
            return True
        return False                       # teq etc. -> .word anyway
    if op == 0x01:                         # REGIMM: full fields printed
        return True
    if op in (0x02, 0x03):                 # j/jal
        return True
    if op in (0x04, 0x05):                 # beq/bne: full fields
        return True
    if op in (0x06, 0x07):                 # blez/bgtz: rt must be 0
        return rt == 0
    if op == 0x0F:                         # lui: rs must be 0
        return rs == 0
    # I-type ALU / memory: every field printed
    if op in (0x08, 0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x0E,
              0x20, 0x21, 0x22, 0x23, 0x24, 0x25, 0x26,
              0x28, 0x29, 0x2A, 0x2B, 0x2E):
        return True
    return False                           # cop/word fallbacks -> .word


def produce_chunk(exe: bytes, addr: int, size: int, tmpdir: Path,
                  verbose: bool = False):
    s_path = gen_chunk_s(exe, addr, size)
    data = assemble_at_va(s_path, addr, tmpdir, verbose=verbose)
    if data is None or len(data) != size:
        return None
    return data


# ---------------------------------------------------------------------------
# C path (level3 pipeline)
# ---------------------------------------------------------------------------

def produce_c(exe: bytes, entry: dict, verbose: bool = False):
    src = ROOT / entry["source"]
    addr = int(entry["address"], 16)
    size = entry["size"]
    if not src.exists():
        return None
    try:
        postproc = parse_postproc_header(src)
        flags = parse_compile_flags(src)
        compiler = parse_compiler(src)
        env = parse_compile_env(src)
        func_bytes = compile_c_function(
            str(src), entry["name"], addr, verbose=False,
            postproc_steps=postproc, extra_flags=flags,
            compiler=compiler, compile_env=env)
    except Exception as e:
        if verbose:
            print(f"    [cc FAIL] {entry['name']}: {e}")
        return None
    if func_bytes is None or len(func_bytes) < size:
        return None
    func_bytes = func_bytes[:size]
    func_bytes = fixup_relocations(func_bytes, addr, exe, file_off(addr))
    return func_bytes


# ---------------------------------------------------------------------------
# cache
# ---------------------------------------------------------------------------

def cache_key(entry: dict, exe: bytes) -> str:
    h = hashlib.sha1()
    h.update(f"main:{CACHE_VERSION}:{entry['name']}:{entry['address']}:"
             f"{entry['size']}".encode())
    src = ROOT / entry["source"]
    try:
        h.update(src.read_bytes())
    except OSError:
        h.update(b"<missing>")
    addr = int(entry["address"], 16)
    h.update(exe[file_off(addr):file_off(addr) + entry["size"]])
    return h.hexdigest()


def cache_load(name: str, key: str):
    p = CACHE_DIR / f"{name}.json"
    try:
        e = json.loads(p.read_text())
        if e.get("key") == key and isinstance(e.get("bytes_hex"), str):
            return bytes.fromhex(e["bytes_hex"]), True
    except (OSError, json.JSONDecodeError, ValueError):
        pass
    return None, False


def cache_store(name: str, key: str, data):
    CACHE_DIR.mkdir(parents=True, exist_ok=True)
    tmp = CACHE_DIR / f".{name}.tmp"
    tmp.write_text(json.dumps(
        {"key": key, "bytes_hex": data.hex() if data is not None else None}))
    tmp.replace(CACHE_DIR / f"{name}.json")


# ---------------------------------------------------------------------------

def produce_cached_c(item):
    """Keep compile/fixup metadata process-local, like build_level3_c.

    compile_c_function publishes LAST_OBJ_INFO; threads can overwrite it
    between compilation and relocation. A worker process runs one pair at
    a time, without sacrificing parallel compilation across functions.
    """
    exe, entry, key, no_cache, verbose = item
    data = produce_c(exe, entry, verbose=verbose)
    addr = int(entry["address"], 16)
    original = exe[file_off(addr):file_off(addr) + entry["size"]]
    if data is not None and data != original:
        data = None
    if not no_cache:
        cache_store(entry["name"], key, data)
    return entry["name"], data


def main():
    import argparse
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--verify", action="store_true")
    ap.add_argument("--allow-rom-fallback", action="store_true",
                    help="splice original bytes for chunks that fail the "
                         "as-path (LOUD debt); otherwise such a chunk fails")
    ap.add_argument("-j", "--jobs", type=int, default=os.cpu_count() or 2,
                    help="parallel workers (default: all cores)")
    ap.add_argument("--no-cache", action="store_true")
    ap.add_argument("-v", "--verbose", action="store_true")
    args = ap.parse_args()
    if args.jobs < 1:
        ap.error("--jobs must be positive")

    os.chdir(ROOT)
    exe = ORIGINAL.read_bytes()
    lv = json.load(open(LEVEL3))
    c_entries = sorted(
        (e for e in lv["functions"] if e["source"].endswith(".c")),
        key=lambda e: int(e["address"], 16))
    print(f"[clean-main] exe {len(exe)} bytes; {len(c_entries)} registered "
          f"byte-perfect C functions")

    out = bytearray(len(exe))
    debt = {"counts": {}, "c_fallback_to_asm": [], "rom_fallback": [],
            "unresolved": []}
    bytes_c = bytes_asm = bytes_rom = 0

    # --- header splice (PS-X EXE metadata) ---
    out[0:FILE_BASE] = exe[0:FILE_BASE]

    # --- C functions (parallel, cached) ---
    t0 = time.monotonic()
    hits = 0
    todo = []
    results = {}
    for e in c_entries:
        key = cache_key(e, exe)
        if not args.no_cache:
            data, hit = cache_load(e["name"], key)
            if hit:
                results[e["name"]] = data
                hits += 1
                continue
        todo.append((exe, e, key, args.no_cache, args.verbose))

    if todo:
        with concurrent.futures.ProcessPoolExecutor(max_workers=args.jobs) \
                as ex:
            for name, data in ex.map(produce_cached_c, todo):
                results[name] = data
    print(f"[clean-main] C phase: {hits} cache hits, {len(todo)} compiled "
          f"({time.monotonic() - t0:.1f}s)")

    c_ok = []
    c_fell = []
    covered = []  # (addr, size) placed by C
    for e in c_entries:
        addr = int(e["address"], 16)
        data = results.get(e["name"])
        if data is not None:
            out[file_off(addr):file_off(addr) + e["size"]] = data
            covered.append((addr, e["size"]))
            bytes_c += e["size"]
            c_ok.append(e["name"])
        else:
            c_fell.append(e["name"])
            debt["c_fallback_to_asm"].append(e["name"])

    # --- everything else: as-path chunks over the uncovered text span ---
    covered.sort()
    spans = []
    cur = TEXT_BASE
    end_addr = TEXT_BASE + (len(exe) - FILE_BASE)
    for addr, size in covered:
        if addr > cur:
            spans.append((cur, addr - cur))
        cur = max(cur, addr + size)
    if cur < end_addr:
        spans.append((cur, end_addr - cur))

    t0 = time.monotonic()
    chunk_jobs = []
    for saddr, ssize in spans:
        a = saddr
        while a < saddr + ssize:
            csize = min(CHUNK, saddr + ssize - a)
            chunk_jobs.append((a, csize))
            a += csize

    def cwork(job):
        a, csize = job
        key = hashlib.sha1(
            f"chunk:{CACHE_VERSION}:{a:08X}:{csize:X}:".encode()
            + exe[file_off(a):file_off(a) + csize]).hexdigest()
        name = f"chunk_{a:08X}"
        if not args.no_cache:
            data, hit = cache_load(name, key)
            if hit:
                return a, csize, data
        with tempfile.TemporaryDirectory() as td:
            data = produce_chunk(exe, a, csize, Path(td),
                                 verbose=args.verbose)
        if data is not None and data != exe[file_off(a):file_off(a) + csize]:
            # round-trip must be exact; a mismatch is an assembler/translator
            # bug — refuse the bytes so the fallback logic reports it
            data = None
        if not args.no_cache and data is not None:
            cache_store(name, key, data)  # never cache failures
        return a, csize, data

    n_chunk_ok = 0
    with concurrent.futures.ThreadPoolExecutor(max_workers=args.jobs) as ex:
        for a, csize, data in ex.map(cwork, chunk_jobs):
            if data is not None:
                out[file_off(a):file_off(a) + csize] = data
                bytes_asm += csize
                n_chunk_ok += 1
            elif args.allow_rom_fallback:
                out[file_off(a):file_off(a) + csize] = \
                    exe[file_off(a):file_off(a) + csize]
                bytes_rom += csize
                debt["rom_fallback"].append(
                    {"addr": f"0x{a:08X}", "size": csize})
            else:
                debt["unresolved"].append(
                    {"addr": f"0x{a:08X}", "size": csize,
                     "note": "as-path chunk failed; rerun with "
                             "--allow-rom-fallback to splice (loud debt)"})
    print(f"[clean-main] as-path: {n_chunk_ok}/{len(chunk_jobs)} chunks "
          f"assembled ({time.monotonic() - t0:.1f}s)")
    if debt["rom_fallback"]:
        print(f"[clean-main] *** ROM FALLBACK USED for "
              f"{len(debt['rom_fallback'])} chunks / {bytes_rom} bytes — "
              f"this is tracked debt, burn it down ***")

    OUT.write_bytes(bytes(out))
    print(f"[clean-main] wrote {OUT}")

    debt["counts"] = {
        "c_functions": len(c_ok),
        "c_fallback_to_asm": len(c_fell),
        "bytes_from_c": bytes_c,
        "bytes_from_asm_roundtrip": bytes_asm,
        "bytes_rom_fallback": bytes_rom,
        "header_bytes_spliced": FILE_BASE,
        "unresolved": len(debt["unresolved"]),
        "note": "bytes_from_asm_roundtrip includes interleaved rodata/data "
                "round-tripped through generated .s (no data/text split "
                "audit for main yet)",
    }

    verify = None
    if args.verify:
        s_orig = sha1(exe)
        s_built = sha1(bytes(out))
        match = s_orig == s_built
        verify = {"sha1_match": match, "sha1_built": s_built,
                  "sha1_original": s_orig, "first_divergence": None}
        if match:
            print(f"[clean-main] VERIFY: BYTE-PERFECT (sha1 {s_built})")
        else:
            first = next(i for i in range(len(exe)) if exe[i] != out[i])
            addr = first - FILE_BASE + TEXT_BASE
            verify["first_divergence"] = {"file_offset": f"0x{first:X}",
                                          "addr": f"0x{addr:08X}"}
            a = first & ~0xF
            print(f"[clean-main] VERIFY: DIVERGES — first at file+0x{first:X}"
                  f" = 0x{addr:08X}")
            print(f"  original: {exe[a:a+16].hex()}")
            print(f"  built:    {bytes(out[a:a+16]).hex()}")

    db = {}
    if DEBT_FILE.exists():
        try:
            db = json.load(open(DEBT_FILE))
        except Exception:
            db = {}
    entry = dict(debt)
    if verify:
        entry["verify"] = verify
    db["main"] = entry
    DEBT_FILE.write_text(json.dumps(db, indent=2, sort_keys=True) + "\n")

    ok = (verify is None or verify["sha1_match"]) and not debt["unresolved"]
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
