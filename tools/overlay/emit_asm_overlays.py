#!/usr/bin/env python3
"""Regenerate the per-function overlay disassembly in `asm/overlay/<OV>/`.

WHY THIS IS NOT TRACKED
-----------------------
Every `asm/overlay/<OV>/<name>.s` is a disassembly of the retail overlay code
that `tools/overlay/extract_exn_functions.py` produces from the player's own
disc. It is therefore a *derived* artefact, not source: holding 9,000 copies of
Konami's bytes in git adds nothing a legal disc image cannot reproduce, and the
2026-11 public-release cleanup untracked them.

WHERE THE NAMES COME FROM
-------------------------
`extract_exn_functions.py` names files `func_<ADDR>.s`; the committed ones carry
the symbol names the decompilation uses. That mapping (overlay, name, address)
plus the SHA-1 of the generated text is recorded in the tracked manifest
`tools/overlay/asm_overlay_manifest.json` -- metadata only, no retail bytes. A
regeneration that does not reproduce the recorded SHA-1 is a hard error, never a
silent rewrite: the manifest is what makes "generated from the disc" checkable.

Files that are NOT in the manifest stay in the repository because the generator
cannot reproduce them:
  * merged multi-symbol windows (marked `/* 0x... (merged block) */`),
  * hand-written thunk fragments without an `Address:` header,
  * gap fragments emitted by `build_clean_exn.py --gen-gap-asm`,
  * a handful of windows the scanner splits differently.
They are listed in `asm/overlay/README.md` categories and `.gitignore` keeps
them tracked.

USAGE
-----
    python3 tools/overlay/emit_asm_overlays.py            # write what is missing
    python3 tools/overlay/emit_asm_overlays.py --force    # rewrite every entry
    python3 tools/overlay/emit_asm_overlays.py --check    # verify, write nothing
    python3 tools/overlay/emit_asm_overlays.py --write-manifest OVERLAY...
"""
import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
ASM_OVERLAY = ROOT / "asm" / "overlay"
MANIFEST = ROOT / "tools" / "overlay" / "asm_overlay_manifest.json"
EXTRACTOR = ROOT / "tools" / "overlay" / "extract_exn_functions.py"
EXN_DIRS = [ROOT / "assets" / "overlays",
            ROOT / "pc" / "assets" / "overlays",
            ROOT / "assets" / "extracted_iso" / "CDROM" / "EXEDIR"]
ADDR_RE = re.compile(r"Address:\s*0x([0-9A-Fa-f]+)")
GLOBL_RE = re.compile(r"\.globl\s+(\S+)")


def exn_path(overlay):
    for d in EXN_DIRS:
        p = d / ("%s.EXN" % overlay)
        if p.is_file():
            return p
    return None


def extract(overlay, tmpdir):
    """Run the tracked extractor; return {load address: generated text}."""
    exn = exn_path(overlay)
    if exn is None:
        return None, "no %s.EXN on disk (extract the overlays from your disc)" % overlay
    out = tmpdir / overlay
    out.mkdir()
    r = subprocess.run([sys.executable, str(EXTRACTOR), str(exn), str(out)],
                       capture_output=True, text=True)
    if r.returncode != 0:
        return None, "extract_exn_functions.py failed: %s" % r.stderr.strip()[-300:]
    by_addr = {}
    for p in sorted(out.glob("*.s")):
        text = p.read_text()
        m = ADDR_RE.search(text)
        if m:
            by_addr[int(m.group(1), 16)] = text
    summaries = {}
    s = out / "SUMMARY.md"
    if s.is_file():
        summaries["SUMMARY.md"] = s.read_text()
    return (by_addr, summaries), None


def sha1(text):
    return hashlib.sha1(text.encode()).hexdigest()


def rename_symbol(text):
    """Return (text with its own symbol name replaced by %s, that name)."""
    m = GLOBL_RE.search(text)
    name = m.group(1) if m else None
    if name is None:
        return text, None
    return text.replace(name, "\x00NAME\x00"), name


def load_manifest():
    return json.loads(MANIFEST.read_text())


def write_manifest(overlays):
    """Rebuild the manifest from the checked-out .s files (one-time / on rename)."""
    tmp = Path(tempfile.mkdtemp(prefix="asmovl_"))
    data = {"comment": ("Generated by tools/overlay/emit_asm_overlays.py "
                        "--write-manifest. Names + addresses + text SHA-1 of the "
                        "regenerable asm/overlay listings; no retail bytes."),
            "generator": "tools/overlay/extract_exn_functions.py",
            "overlays": {}}
    skipped = []
    for overlay in overlays:
        gen, err = extract(overlay, tmp)
        if err:
            print("%s: %s" % (overlay, err))
            return 1
        by_addr, summaries = gen
        entries = []
        for s in sorted((ASM_OVERLAY / overlay).glob("*.s")):
            text = s.read_text()
            m = ADDR_RE.search(text)
            if not m:
                skipped.append("%s/%s (no Address header)" % (overlay, s.name))
                continue
            addr = int(m.group(1), 16)
            g = by_addr.get(addr)
            if g is None:
                skipped.append("%s/%s (no generated file at 0x%08X)"
                               % (overlay, s.name, addr))
                continue
            a, _ = rename_symbol(text)
            b, _ = rename_symbol(g)
            if a != b:
                skipped.append("%s/%s (text differs)" % (overlay, s.name))
                continue
            entries.append({"name": s.name, "addr": "0x%08X" % addr,
                            "symbol": GLOBL_RE.search(text).group(1),
                            "sha1": sha1(text)})
        data["overlays"][overlay] = {"files": entries,
                                     "summaries": dict(
                                         (n, sha1(t)) for n, t in summaries.items())}
    MANIFEST.write_text(json.dumps(data, indent=1, sort_keys=True) + "\n")
    print("wrote %s: %d overlay(s), %d file(s)"
          % (MANIFEST.relative_to(ROOT), len(data["overlays"]),
             sum(len(v["files"]) for v in data["overlays"].values())))
    print("kept out of the manifest (hand-authored): %d file(s)" % len(skipped))
    for line in skipped:
        print("  " + line)
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true",
                    help="rewrite entries that already exist")
    ap.add_argument("--check", action="store_true",
                    help="verify against the manifest, write nothing")
    ap.add_argument("--write-manifest", nargs="*", metavar="OVERLAY",
                    help="regenerate the manifest from the checked-out tree")
    ap.add_argument("--only", action="append", default=[], metavar="OVERLAY")
    args = ap.parse_args()

    if args.write_manifest is not None:
        names = args.write_manifest or sorted(p.name for p in ASM_OVERLAY.iterdir()
                                              if p.is_dir())
        return write_manifest(names)

    manifest = load_manifest()
    overlays = sorted(manifest["overlays"])
    if args.only:
        overlays = [o for o in overlays if o in args.only]
    tmp = Path(tempfile.mkdtemp(prefix="asmovl_"))
    bad = writing = present = 0
    try:
        for overlay in overlays:
            gen, err = extract(overlay, tmp)
            if err:
                print("ERROR %s: %s" % (overlay, err))
                return 1
            by_addr, summaries = gen
            for entry in manifest["overlays"][overlay]["files"]:
                addr = int(entry["addr"], 16)
                out = ASM_OVERLAY / overlay / entry["name"]
                g = by_addr.get(addr)
                if g is None:
                    print("ERROR %s/%s: generator produced no file at 0x%08X"
                          % (overlay, entry["name"], addr))
                    return 1
                text = g.replace(GLOBL_RE.search(g).group(1), entry["symbol"])
                if sha1(text) != entry["sha1"]:
                    print("ERROR %s/%s: regenerated text SHA-1 %s != manifest %s"
                          % (overlay, entry["name"], sha1(text)[:12],
                             entry["sha1"][:12]))
                    return 1
                if args.check:
                    if out.is_file() and sha1(out.read_text()) == entry["sha1"]:
                        present += 1
                    else:
                        print("MISSING/STALE %s/%s" % (overlay, entry["name"]))
                        bad += 1
                    continue
                if out.is_file() and not args.force:
                    present += 1
                    continue
                out.parent.mkdir(parents=True, exist_ok=True)
                out.write_text(text)
                writing += 1
            for sname, want in sorted(
                    manifest["overlays"][overlay].get("summaries", {}).items()):
                out = ASM_OVERLAY / overlay / sname
                got = sha1(summaries[sname]) if sname in summaries else None
                if got != want:
                    print("ERROR %s/%s: regenerated SHA-1 %s != manifest %s"
                          % (overlay, sname, (got or "none")[:12], want[:12]))
                    return 1
                if args.check:
                    if out.is_file() and sha1(out.read_text()) == want:
                        present += 1
                    else:
                        print("MISSING/STALE %s/%s" % (overlay, sname))
                        bad += 1
                    continue
                if out.is_file() and not args.force:
                    present += 1
                    continue
                out.write_text(summaries[sname])
                writing += 1
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    if args.check:
        print("%d manifest file(s) verified, %d missing/stale" % (present, bad))
        return 1 if bad else 0
    print("%d file(s) written, %d already present" % (writing, present))
    # the other disc-derived input the overlay C needs: the TXT_<ADDR>
    # string literals (include/overlay_text/<OV>.h, gitignored game text)
    return subprocess.call([sys.executable, str(Path(__file__).resolve()
                                                .parent / "gen_overlay_text.py")])


if __name__ == "__main__":
    sys.exit(main())