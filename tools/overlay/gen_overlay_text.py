#!/usr/bin/env python3
"""gen_overlay_text.py - the overlays' message text, from the player's disc.

A matched overlay function writes a string literal as `TXT_<ADDR>`, the
address its bytes occupy in the retail overlay.  Game text is Konami's
creative content and never enters the repository
(docs/CLEAN-DISK-BUILD-SPEC.md, project decision D4), so this tool generates
the gitignored header include/overlay_text/<OV>.h from the extraction
assets/overlays/<OV>.EXN:

    #define TXT_801340D0 "\\x97\\xFB\\x8F\\x4B\\x8E\\x8E\\x8D\\x87"

After preprocessing the compiler sees an ordinary literal, so IDO places it
in the function's own .rodata literal pool exactly as the original source
did (docs/reference/OVERLAY-DATA-FROM-SOURCE.md).  The PC port maps each
TXT_<ADDR> back to the PS1 object at ADDR (generate_overlay_modules.py).

Usage:
    python3 tools/overlay/gen_overlay_text.py            # every overlay
    python3 tools/overlay/gen_overlay_text.py RENSYU     # one overlay
    python3 tools/overlay/gen_overlay_text.py --check    # exit 1 if stale
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
SRC = ROOT / "src" / "overlay"
EXN = ROOT / "assets" / "overlays"
OUT = ROOT / "include" / "overlay_text"
BASE = 0x80132000
TXT_RE = re.compile(r"\bTXT_([0-9A-F]{8})\b")


def overlay_tokens(ov: str):
    addrs = set()
    for c in sorted((SRC / ov).rglob("*.c")):
        addrs |= {int(a, 16) for a in TXT_RE.findall(c.read_text(errors="ignore"))}
    return sorted(addrs)


def render(ov: str) -> str:
    addrs = overlay_tokens(ov)
    if not addrs:
        return ""
    data = (EXN / f"{ov}.EXN").read_bytes()
    lines = [f"/* GENERATED by tools/overlay/gen_overlay_text.py from the "
             f"player's {ov}.EXN -- game text, never commit. */",
             f"#ifndef OVERLAY_TEXT_{ov}_H", f"#define OVERLAY_TEXT_{ov}_H"]
    for a in addrs:
        off = a - BASE
        if not 0 <= off < len(data):
            raise SystemExit(f"{ov}: TXT_{a:08X} is outside the overlay")
        end = data.index(b"\0", off)
        body = "".join(f"\\x{b:02X}" for b in data[off:end])
        lines.append(f'#define TXT_{a:08X} "{body}"')
    lines.append("#endif")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("overlays", nargs="*")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    ovs = [o.upper() for o in args.overlays] or \
        sorted(p.name for p in SRC.iterdir() if p.is_dir())
    stale = 0
    for ov in ovs:
        text = render(ov)
        path = OUT / f"{ov}.h"
        if not text:
            continue
        if args.check:
            if not path.exists() or path.read_text() != text:
                print(f"STALE {path.relative_to(ROOT)}")
                stale += 1
            continue
        OUT.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)} ({text.count('#define TXT_')} strings)")
    sys.exit(1 if stale else 0)


if __name__ == "__main__":
    main()
