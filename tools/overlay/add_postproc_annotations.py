#!/usr/bin/env python3
"""
Add @PostProc annotations to overlay C files that need them.
Reads the list of functions and adds the appropriate annotations.
"""

import os
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).parent.parent.parent
SRC_DIR = ROOT / "src" / "overlay"
ASM_DIR = ROOT / "asm" / "overlay"
IDO_CC = ROOT / "tools" / "ido-static-recomp" / "build" / "5.2" / "out" / "cc"

def get_target_insn_count(asm_file: Path) -> int:
    """Extract target instruction count from ASM file header."""
    try:
        with open(asm_file, 'r') as f:
            content = f.read(500)
        match = re.search(r'Size: \d+ bytes \((\d+) instructions?\)', content)
        if match:
            return int(match.group(1))
    except:
        pass
    return 0

def get_compiled_insn_count(c_file: Path) -> int:
    """Compile and count instructions."""
    obj_file = Path("/tmp/test_postproc.o")
    cmd = [
        str(IDO_CC), "-O2", "-G0", "-mips1", "-EL", "-non_shared",
        f"-I{ROOT / 'include'}", "-c", str(c_file), "-o", str(obj_file)
    ]
    try:
        result = subprocess.run(cmd, capture_output=True, timeout=30)
        if result.returncode != 0:
            return 0
        # Count instructions
        result = subprocess.run(
            ["mipsel-linux-gnu-objdump", "-d", str(obj_file)],
            capture_output=True, text=True
        )
        return len(re.findall(r'^\s+[0-9a-f]+:', result.stdout, re.MULTILINE))
    except:
        return 0

def add_postproc_annotation(c_file: Path, annotation: str) -> bool:
    """Add @PostProc annotation to C file if not present."""
    try:
        with open(c_file, 'r') as f:
            content = f.read()

        if f"@PostProc: {annotation}" in content:
            return False  # Already has it

        # Add after Semi-matched line or Size line
        if "* Semi-matched" in content:
            content = content.replace(
                "* Semi-matched",
                f"* Semi-matched\n * @PostProc: {annotation}"
            )
        elif re.search(r'\* Size: \d+ bytes', content):
            content = re.sub(
                r'(\* Size: \d+ bytes[^\n]*\n)',
                r'\1 * @PostProc: ' + annotation + '\n',
                content
            )
        else:
            return False

        with open(c_file, 'w') as f:
            f.write(content)
        return True
    except:
        return False

def find_trailing_nop_functions():
    """Find all functions that need strip_trailing_nop."""
    results = []

    for overlay_dir in sorted(SRC_DIR.iterdir()):
        if not overlay_dir.is_dir():
            continue
        overlay_name = overlay_dir.name
        asm_overlay_dir = ASM_DIR / overlay_name

        for c_file in sorted(overlay_dir.glob("*.c")):
            func_name = c_file.stem
            asm_file = asm_overlay_dir / f"{func_name}.s"

            if not asm_file.exists():
                continue

            target = get_target_insn_count(asm_file)
            if target == 0:
                continue

            compiled = get_compiled_insn_count(c_file)
            if compiled == 0:
                continue

            diff = compiled - target
            if diff == 1:
                results.append((overlay_name, func_name, c_file))

    return results

def main():
    print("Finding functions that need strip_trailing_nop...")
    functions = find_trailing_nop_functions()
    print(f"Found {len(functions)} functions with +1 diff")

    added = 0
    for overlay, func, c_file in functions:
        if add_postproc_annotation(c_file, "strip_trailing_nop"):
            print(f"  Added @PostProc to {overlay}/{func}")
            added += 1

    print(f"\nAdded annotations to {added} files")

    # Write config file
    config_file = ROOT / "config" / "overlay_strip_trailing_nop.txt"
    config_file.parent.mkdir(parents=True, exist_ok=True)
    with open(config_file, 'w') as f:
        f.write("# Overlay functions that need strip_trailing_nop PostProc\n")
        f.write("# Generated by add_postproc_annotations.py\n\n")
        for overlay, func, _ in functions:
            f.write(f"{overlay}/{func}\n")
    print(f"Wrote config to {config_file}")

if __name__ == "__main__":
    main()
