#!/usr/bin/env python3
"""
generate_linker.py - Generate linker scripts for EXN overlays

Reads symbol maps from config/overlay/*.sym and generates
linker scripts that place functions at correct addresses.

Usage:
    python3 tools/overlay/generate_linker.py OPTION
    python3 tools/overlay/generate_linker.py --all

Output:
    build/overlay/OPTION/linker.ld
"""

import os
import sys
from pathlib import Path
from typing import List, Tuple

# Project root
ROOT = Path(__file__).parent.parent.parent

# Paths
CONFIG_DIR = ROOT / "config" / "overlay"
BUILD_DIR = ROOT / "build" / "overlay"

# Overlay size (192KB) and base address
OVERLAY_SIZE = 192 * 1024
OVERLAY_BASE = 0x80132000


def parse_symbol_file(path: Path) -> List[Tuple[int, int, str]]:
    """Parse symbol file, return list of (addr, size, name) tuples"""
    symbols = []

    for line in path.read_text().split('\n'):
        line = line.strip()
        if not line or line.startswith('#'):
            continue

        # Format: 0xADDRESS:SIZE:NAME
        parts = line.split(':')
        if len(parts) >= 3:
            try:
                addr = int(parts[0], 16)
                size = int(parts[1])
                name = parts[2]
                symbols.append((addr, size, name))
            except ValueError:
                continue

    return sorted(symbols, key=lambda x: x[0])


def generate_linker_script(overlay_name: str, symbols: List[Tuple[int, int, str]]) -> str:
    """Generate GNU ld linker script"""

    # Calculate end of text section
    if symbols:
        last_func = symbols[-1]
        text_end = last_func[0] + last_func[1]
    else:
        text_end = OVERLAY_BASE + 0x1000

    lines = [
        f"/* Linker script for {overlay_name}.EXN */",
        f"/* Generated by generate_linker.py */",
        f"/* Functions should be linked in address order */",
        "",
        "OUTPUT_FORMAT(\"elf32-tradlittlemips\")",
        "OUTPUT_ARCH(mips)",
        "",
        "MEMORY {",
        f"    overlay : ORIGIN = 0x{OVERLAY_BASE:08X}, LENGTH = {OVERLAY_SIZE}",
        "}",
        "",
        "SECTIONS {",
        f"    . = 0x{OVERLAY_BASE:08X};",
        "",
        "    .text : {",
        "        /* All .text sections - linker combines in input order */",
        "        *(.text*)",
        "    } > overlay",
        "",
        "    .rodata : {",
        "        *(.rodata*)",
        "    } > overlay",
        "",
        "    .data : {",
        "        *(.data*)",
        "    } > overlay",
        "",
        "    .bss : {",
        "        *(.bss*)",
        "        *(COMMON)",
        "    } > overlay",
        "",
        "    /* Discard debug info */",
        "    /DISCARD/ : {",
        "        *(.comment)",
        "        *(.pdr)",
        "        *(.mdebug*)",
        "        *(.reginfo)",
        "        *(.MIPS.abiflags)",
        "    }",
        "}",
    ]

    return "\n".join(lines)


def process_overlay(name: str) -> bool:
    """Process a single overlay and generate linker script"""
    sym_path = CONFIG_DIR / f"{name}.sym"

    if not sym_path.exists():
        print(f"[{name}] ERROR: Symbol file not found: {sym_path}")
        return False

    print(f"[{name}] Reading symbol map...")
    symbols = parse_symbol_file(sym_path)
    print(f"[{name}] Found {len(symbols)} symbols")

    # Generate linker script
    script = generate_linker_script(name, symbols)

    # Write output
    output_dir = BUILD_DIR / name
    output_dir.mkdir(parents=True, exist_ok=True)
    output_path = output_dir / "linker.ld"

    output_path.write_text(script)
    print(f"[{name}] Wrote {output_path}")

    return True


def get_all_overlays() -> List[str]:
    """Get list of all overlay names from symbol files"""
    overlays = []
    if CONFIG_DIR.exists():
        for sym_file in CONFIG_DIR.glob("*.sym"):
            overlays.append(sym_file.stem)
    return sorted(overlays)


def main():
    if len(sys.argv) < 2:
        print("Usage: python3 tools/overlay/generate_linker.py <OVERLAY_NAME>")
        print("       python3 tools/overlay/generate_linker.py --all")
        print("")
        print("Available overlays (from config/overlay/*.sym):")
        for name in get_all_overlays():
            print(f"  {name}")
        sys.exit(1)

    if sys.argv[1] == "--all":
        overlays = get_all_overlays()
        success = 0
        for name in overlays:
            if process_overlay(name):
                success += 1
        print(f"\n[DONE] Generated {success}/{len(overlays)} linker scripts")
    else:
        name = sys.argv[1].upper()
        if not process_overlay(name):
            sys.exit(1)

    print("\n[DONE] Linker scripts written to build/overlay/*/linker.ld")


if __name__ == "__main__":
    main()
