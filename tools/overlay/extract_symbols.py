#!/usr/bin/env python3
"""
extract_symbols.py - Extract function symbols from EXN overlay

Analyzes an EXN overlay binary and generates a symbol map by:
1. Finding function prologues (addiu sp, sp, -N)
2. Matching with existing C source files
3. Generating linker-compatible symbol list

Usage:
    python3 tools/overlay/extract_symbols.py OPTION
    python3 tools/overlay/extract_symbols.py --all

Output:
    config/overlay/OPTION.sym
"""

import os
import sys
import struct
from pathlib import Path
from typing import List, Tuple, Dict

# Project root
ROOT = Path(__file__).parent.parent.parent

# Paths
OVERLAYS_DIR = ROOT / "assets" / "overlays"
OVERLAYS_ALT = ROOT / "assets" / "extracted_iso" / "CDROM" / "EXEDIR"
SRC_OVERLAY_DIR = ROOT / "src" / "overlay"
CONFIG_DIR = ROOT / "config" / "overlay"

# Overlay base address
OVERLAY_BASE = 0x80132000


def find_overlay_binary(name: str) -> Path:
    """Find overlay EXN file"""
    # Try assets/overlays first
    exn = OVERLAYS_DIR / f"{name}.EXN"
    if exn.exists():
        return exn

    # Try extracted_iso path
    exn = OVERLAYS_ALT / f"{name}.EXN"
    if exn.exists():
        return exn

    raise FileNotFoundError(f"Overlay not found: {name}.EXN")


def find_function_prologues(data: bytes) -> List[Tuple[int, int]]:
    """
    Find function prologues by looking for 'addiu sp, sp, -N' instructions.
    Returns list of (offset, frame_size) tuples.

    MIPS addiu sp, sp, imm:
        opcode = 0x27BD (addiu $sp, $sp)
        Format: 0x27BDXXXX where XXXX is signed 16-bit immediate (negative for prologue)
    """
    prologues = []

    for i in range(0, len(data) - 4, 4):
        insn = struct.unpack('<I', data[i:i+4])[0]

        # Check for addiu sp, sp, -N (0x27BDxxxx where xxxx is negative)
        if (insn >> 16) == 0x27BD:
            imm = insn & 0xFFFF
            # Check if it's a negative value (prologue)
            if imm >= 0x8000:  # Sign bit set = negative
                frame_size = 0x10000 - imm  # Convert to positive
                if 8 <= frame_size <= 2048:  # Reasonable frame sizes
                    prologues.append((i, frame_size))

    return prologues


def get_source_functions(overlay_name: str) -> Dict[str, int]:
    """
    Get function names and estimated sizes from C source files.
    Returns dict of name -> approx_size (in bytes, estimated from line count)
    """
    src_dir = SRC_OVERLAY_DIR / overlay_name
    if not src_dir.exists():
        return {}

    functions = {}
    for c_file in src_dir.glob("*.c"):
        # Extract function name from filename
        func_name = c_file.stem  # e.g., "func_80132000"

        # Count lines as rough size estimate (4 bytes per line average)
        try:
            lines = len(c_file.read_text().split('\n'))
            estimated_size = lines * 4  # Very rough estimate
            functions[func_name] = estimated_size
        except:
            functions[func_name] = 100  # Default

    return functions


def match_functions_to_offsets(
    prologues: List[Tuple[int, int]],
    source_functions: Dict[str, int]
) -> List[Tuple[int, str, int]]:
    """
    Match source function names to binary offsets.
    Returns list of (offset, name, frame_size) sorted by offset.
    """
    results = []

    # Sort source functions by their address (from name)
    sorted_funcs = []
    for name in source_functions:
        # Extract address from func_XXXXXXXX
        if name.startswith("func_"):
            try:
                addr = int(name[5:], 16)
                sorted_funcs.append((addr, name))
            except ValueError:
                pass

    sorted_funcs.sort()

    # For each prologue, find matching function name
    for offset, frame_size in prologues:
        addr = OVERLAY_BASE + offset

        # Find closest function name
        best_name = None
        best_diff = 0x1000  # Max 4KB difference

        for func_addr, func_name in sorted_funcs:
            diff = abs(addr - func_addr)
            if diff < best_diff:
                best_diff = diff
                best_name = func_name

        if best_name and best_diff < 0x100:  # Within 256 bytes
            results.append((offset, best_name, frame_size))
        else:
            # Generate name from address
            auto_name = f"func_{addr:08X}"
            results.append((offset, auto_name, frame_size))

    return sorted(results, key=lambda x: x[0])


def generate_symbol_file(
    overlay_name: str,
    functions: List[Tuple[int, str, int]],
    data_size: int
) -> str:
    """Generate symbol map file content"""
    lines = [
        f"# {overlay_name}.EXN symbol map",
        f"# Generated by extract_symbols.py",
        f"# Base address: 0x{OVERLAY_BASE:08X}",
        "",
        "# Format: address:size:name",
        "",
        "# === Functions ===",
    ]

    # Calculate sizes from offsets
    for i, (offset, name, frame) in enumerate(functions):
        addr = OVERLAY_BASE + offset

        # Size is distance to next function or end of .text
        if i + 1 < len(functions):
            size = functions[i + 1][0] - offset
        else:
            # Last function - estimate from frame size
            size = max(frame * 4, 0x40)  # At least 64 bytes

        lines.append(f"0x{addr:08X}:{size}:{name}")

    # Add data section estimate
    if data_size > 0:
        lines.extend([
            "",
            "# === Data (estimated) ===",
            f"# Data section starts after .text, approximately {data_size} bytes"
        ])

    return "\n".join(lines)


def process_overlay(name: str) -> bool:
    """Process a single overlay and generate symbol map"""
    print(f"[{name}] Processing overlay...")

    # This tool REGENERATES the .sym with address names only.  The .sym maps are
    # hand-curated tracked source, and once apply_overlay_symbols.py has landed
    # a real name here, regenerating would silently drop it (the C, the status
    # JSON and the name table would then disagree with the .sym).
    sys.path.insert(0, str(ROOT / "tools" / "overlay"))
    import overlay_names
    landed = overlay_names.overlay_table(name)
    if landed and os.environ.get("EXTRACT_SYMBOLS_FORCE") != "1":
        print(f"[{name}] REFUSED: {len(landed)} landed overlay name(s) "
              f"({', '.join(sorted(landed)[:3])}...) would be lost; "
              "revert them first (apply_overlay_symbols.py --revert) "
              "or set EXTRACT_SYMBOLS_FORCE=1")
        return False

    try:
        exn_path = find_overlay_binary(name)
    except FileNotFoundError as e:
        print(f"[{name}] ERROR: {e}")
        return False

    # Read binary
    data = exn_path.read_bytes()
    print(f"[{name}] Binary size: {len(data)} bytes")

    # Find function prologues
    prologues = find_function_prologues(data)
    print(f"[{name}] Found {len(prologues)} function prologues")

    # Get source functions
    source_funcs = get_source_functions(name)
    print(f"[{name}] Found {len(source_funcs)} source functions")

    # Match
    functions = match_functions_to_offsets(prologues, source_funcs)
    print(f"[{name}] Matched {len(functions)} functions")

    # Estimate data section size (total - text)
    if functions:
        text_end = functions[-1][0] + 0x100  # Rough estimate
        data_size = len(data) - text_end - 4  # Minus checksum
    else:
        data_size = 0

    # Generate output
    CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    output_path = CONFIG_DIR / f"{name}.sym"

    content = generate_symbol_file(name, functions, data_size)
    output_path.write_text(content)

    print(f"[{name}] Wrote {output_path}")
    return True


def get_all_overlays() -> List[str]:
    """Get list of all overlay names"""
    overlays = []

    # From source directory
    if SRC_OVERLAY_DIR.exists():
        for d in SRC_OVERLAY_DIR.iterdir():
            if d.is_dir() and not d.name.startswith('.'):
                overlays.append(d.name)

    return sorted(set(overlays))


def main():
    if len(sys.argv) < 2:
        print("Usage: python3 tools/overlay/extract_symbols.py <OVERLAY_NAME>")
        print("       python3 tools/overlay/extract_symbols.py --all")
        print("")
        print("Available overlays:")
        for name in get_all_overlays():
            print(f"  {name}")
        sys.exit(1)

    if sys.argv[1] == "--all":
        overlays = get_all_overlays()
        success = 0
        for name in overlays:
            if process_overlay(name):
                success += 1
        print(f"\n[DONE] Processed {success}/{len(overlays)} overlays")
    else:
        name = sys.argv[1].upper()
        if not process_overlay(name):
            sys.exit(1)

    print("\n[DONE] Symbol maps written to config/overlay/")


if __name__ == "__main__":
    main()
