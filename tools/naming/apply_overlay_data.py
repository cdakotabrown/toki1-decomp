#!/usr/bin/env python3
"""Land reviewed OVERLAY DATA names (records written by record_overlay_data.py)
into the tree: the overlay sibling of tools/analysis/apply_data_symbols.py.

A pending record

    "DATE:0x8015B66C": {"name": "date_end_code", "kind": "data", "scope": "DATE",
                        ..., "evidence": "...reviewed:consistent (...)", "landed": false}

is landed by a whole-word, hex-case-insensitive replacement of `D_8015B66C`
by `date_end_code`, SCOPED TO THAT OVERLAY: every overlay loads at 0x80132000,
so the same address is a different object in another overlay and is never
touched there.  Files rewritten:

  * src/overlay/<OV>/**            the C (externs keep their own types and bounds)
  * pc/src/overlay/<OV>/**         hand-written PC overlay files
  * pc/src/overlay_inits/overlay_init_<OV>.c
  * pc/tools/*_plan.json
                                   the PC source-edit plans: entries keyed
                                   `<OV>/<func>` quote C source verbatim, and the
                                   module generator refuses a stale quote
pc/src/overlay_<OV>.c is GENERATED (pc/tools/generate_overlay_modules.py) and
is regenerated by the landing script, not edited here.

Where an overlay data name is bound to its address (read before writing this):
  * tools/overlay/overlay_names.py (the resolver's name table) reads every
    landed `kind: data` record of the overlay's scope -- so the EXN link and
    the byte verifier find the address through config/symbol_names.json;
  * pc/ld/psx_globals.syms (the PC globals model, absolute addresses) needs
    `name = 0xADDR;`: tools/naming/sync_psx_globals.py --only OV:0xADDR adds it;
  * `@StaticAddr: D_X 0xX` headers carry the address next to the name.
  * asm/overlay/** addresses memory by number (no binding).

The PC port links every overlay module into one binary, so an overlay data name
must be unique across ALL scopes (record_overlay_data.py's fence already
enforces that for the ledger; this tool re-checks the tree).

Refused (printed with the reason, nothing written for that record):
  * not a pending overlay `kind: data` record of --ov; no reviewed:consistent;
  * the name is address-shaped, already a landed name anywhere, or appears as
    code (comments stripped) anywhere in src/ include/ pc/ (outside pc/3rd);
  * no file of the overlay carries the D_ token (nothing would verify it);
  * a touched file is git-modified (being edited elsewhere) and not --allow-locked.

usage: apply_overlay_data.py --ov OV [--only OV:0xADDR ...] (--dry-run | --apply)
                             [--allow-locked PATH ...]
"""
import argparse
import glob
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'analysis'))
import symbol_names as SN  # noqa: E402

ADDR_NAME = re.compile(r'^(?:D|func|FUN)_[0-9A-Fa-f]{8}$')
TEXT_EXT = ('.c', '.h', '.inc', '.s')


def git(*a):
    return subprocess.run(['git'] + list(a), capture_output=True, text=True, cwd=ROOT).stdout


def word(name, ic=False):
    return re.compile(r'(?<![A-Za-z0-9_])' + re.escape(name) + r'(?![A-Za-z0-9_])',
                      re.I if ic else 0)


def strip_comments(t):
    return re.sub(r'//[^\n]*', ' ', re.sub(r'/\*.*?\*/', ' ', t, flags=re.S))


def read(p):
    try:
        return open(os.path.join(ROOT, p), encoding='utf-8').read()
    except (OSError, UnicodeDecodeError):
        return None


def scope_files(ov, token):
    roots = [f'src/overlay/{ov}/', f'pc/src/overlay/{ov}/', f'pc/src/overlay_inits/overlay_init_{ov}.c']
    out = git('grep', '--untracked', '-I', '-l', '-i', '-w', '-F', token, '--', *roots).split()
    return sorted(p for p in out if p.endswith(TEXT_EXT))


# every PC source-edit plan (a fixed list missed stack_width_plan.json when it
# was added: KANGEI 2026-11-09)
PLANS = sorted(glob.glob(os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__)))), 'pc', 'tools', '*_plan.json')))
PLANS = [os.path.relpath(x, os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))) for x in PLANS]


def rename_in_plans(ov, token, name, apply):
    """rename TOKEN inside the plan entries keyed OV/...; returns touched plan paths"""
    import json
    touched = []
    for p in PLANS:
        path = os.path.join(ROOT, p)
        if not os.path.exists(path):
            continue
        raw = open(path).read()
        doc = json.loads(raw)
        n = 0
        for k, v in list(doc.get('functions', {}).items()):
            if not k.startswith(ov + '/'):
                continue
            s = json.dumps(v)
            s2, k2 = word(token, ic=True).subn(name, s)
            if k2:
                doc['functions'][k] = json.loads(s2)
                n += k2
        if n:
            touched.append(p)
            if apply:
                out = json.dumps(doc, indent=2)
                open(path, 'w').write(out + ('\n' if raw.endswith('\n') else ''))
    return touched


def code_use_anywhere(name):
    """files using NAME as code (comments stripped), outside vendor trees."""
    hits = git('grep', '--untracked', '-I', '-l', '-w', '-F', name, '--', 'src', 'include', 'pc').split()
    out = []
    for p in hits:
        if p.startswith('pc/3rd/') or p.endswith('.md'):
            continue
        t = read(p)
        if t is not None and word(name).search(strip_comments(t)):
            out.append(p)
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--ov', required=True)
    ap.add_argument('--only', action='append', default=[])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument('--dry-run', action='store_true')
    g.add_argument('--apply', action='store_true')
    ap.add_argument('--allow-locked', action='append', default=[])
    a = ap.parse_args()
    ov = a.ov
    doc = SN.load_names(all_scopes=True)
    syms = doc['symbols']
    only = {SN.norm_key(k if ':' in k else f'{ov}:{k}') for k in a.only}
    landed_names = {e['name'] for e in syms.values() if e.get('landed')}
    dirty = {l[3:].strip() for l in git('status', '--porcelain', '--untracked-files=no').splitlines()}
    done, refused, touched = [], 0, set()
    for key, e in sorted(syms.items(), key=SN._sort_key):
        if e.get('scope') != ov or e.get('kind') != 'data' or e.get('landed'):
            continue
        if only and key not in only:
            continue
        addr = int(key.split(':')[1], 16)
        name, token = e['name'], f'D_{addr:08X}'
        why = []
        if 'reviewed:consistent' not in e.get('evidence', ''):
            why.append('no reviewed:consistent verdict')
        if ADDR_NAME.match(name):
            why.append('address-shaped name')
        if name in landed_names:
            why.append('name already landed elsewhere')
        uses = code_use_anywhere(name)
        if uses:
            why.append(f'name already used as code: {uses[:3]}')
        files = scope_files(ov, token)
        if not files:
            why.append(f'no {ov} file carries {token}')
        locked = [f for f in files if f in dirty and f not in a.allow_locked]
        if locked:
            why.append(f'touches git-modified files {locked[:3]}')
        if why:
            refused += 1
            print(f'REFUSE {key} {token} -> {name}: ' + '; '.join(why))
            continue
        print(f'{"LAND" if a.apply else "WOULD"} {key} {token} -> {name}: {len(files)} files')
        if a.apply:
            n = 0
            for f in files:
                t = read(f)
                t2, k = word(token, ic=True).subn(name, t)
                if k:
                    open(os.path.join(ROOT, f), 'w', encoding='utf-8').write(t2)
                    n += k
                    touched.add(f)
            plans = rename_in_plans(ov, token, name, True)
            touched.update(plans)
            files = files + plans
            e['landed'] = True
            e['landed_files'] = files
            e['evidence'] = e.get('evidence', '') + f'; landed {SN.TODAY} by apply_overlay_data.py ({len(files)} files, {n} references)'
            landed_names.add(name)
        done.append(key)
        # survivors: any remaining token in the scope means a missed spelling
    if a.apply and done:
        SN.save_names(doc)
        for key in done:
            addr = int(key.split(':')[1], 16)
            left = scope_files(ov, f'D_{addr:08X}')
            if left:
                print(f'SURVIVOR {key}: {left[:4]}')
    print(f'{ov}: {len(done)} {"landed" if a.apply else "would land"}, {refused} refused')
    if touched:
        print('touched paths')
        for t in sorted(touched):
            print('  ' + t)
    return 0 if not refused else 1


if __name__ == '__main__':
    sys.exit(main())
