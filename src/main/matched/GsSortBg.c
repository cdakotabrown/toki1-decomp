#include "types.h"
#include "psyq/stddef.h"
#include "psyq/libgte.h"

typedef struct {
    unsigned char u, v;
    unsigned short cba;
    unsigned short flag;
    unsigned short tpage;
} GsCELL;

typedef struct {
    unsigned char cellw, cellh;
    unsigned short ncellw, ncellh;
    GsCELL *base;
    unsigned short *index;
} GsMAP;

typedef struct {
    unsigned long attribute;
    short x, y;
    short w, h;
    short scrollx, scrolly;
    unsigned char r, g, b;
    GsMAP *map;
    short mx, my;
    short scalex, scaley;
    long rotate;
} GsBG;

typedef struct {
    u8  code;
    u8  r, g, b;
    u16 tpage;
    u16 clut;
    u8  u;
    u8  v;
    s16 x;
    s16 y;
    u16 w;
    s16 h;
    s16 mx;
    s16 my;
    u16 flag;
    s32 useMatrix;
} BgCellParams;

typedef struct {
    u32  length;
    u32 *org;
    s32  offset;
} SortOT;

extern u8 *GsOUT_PACKET_P;
extern MATRIX GsIDMATRIX;

extern void gte_rotate_z_matrix(MATRIX *m, s32 rotate);
extern void gte_scale_matrix(MATRIX *m, s16 sx, s16 sy, s32 sz);
extern s16  _mk_spr_packet(u8 *dest, BgCellParams *p, MATRIX *m, GsCELL *cell);

void GsSortBg(GsBG *bg, SortOT *otp, u16 pri)
{
    MATRIX mtx;
    BgCellParams params;
    u32 attr;
    u16 blendBits;
    s32 clipW, clipH;
    s32 totalW, totalH;
    u16 tileW, tileH;
    u16 mapW, mapH;
    u8 *pk;
    s32 rowStartX;
    s32 baseY;
    s32 curY;
    s32 screenY;
    s32 tileHi;
    s32 colEndY;
    s32 rowEndX;
    u16 chunkH;
    s32 vOff;
    s32 tileWi;
    s32 mapWm;
    s32 idx;
    u32 *bucket;
    u16 sv;
    s32 th;
    s32 slot;

    attr = bg->attribute;
    if ((s32)attr < 0) {
        return;
    }
    if (bg->map->ncellw == 0) {
        return;
    }
    if (bg->map->ncellh == 0) {
        return;
    }

    tileW = bg->map->cellw;
    if (tileW == 0) {
        tileW = 0x100;
    }
    tileH = bg->map->cellh;
    if (tileH == 0) {
        tileH = 0x100;
    }
    mapW = bg->map->ncellw;
    mapH = bg->map->ncellh;

    totalW = tileW * mapW;
    totalH = tileH * mapH;
    params.code = (((attr >> 0x1D) & 2) | 0x2C) | ((attr >> 6) & 1);
    params.r = bg->r;
    blendBits = ((attr >> 0x11) & 0x180) | ((attr >> 0x17) & 0x60);
    params.g = bg->g;
    params.b = bg->b;

    if ((attr & 0x08000000) ||
        (*(u32 *)&bg->scalex == 0x10001000 && bg->rotate == 0)) {
        params.useMatrix = 0;
    } else {
        params.useMatrix = 1;
        mtx = GsIDMATRIX;
        gte_rotate_z_matrix(&mtx, bg->rotate);
        gte_scale_matrix(&mtx, bg->scalex, bg->scaley, 0x1000);
    }

    pk = GsOUT_PACKET_P;
    rowStartX = bg->scrollx % totalW;
    clipW = bg->w;
    do { th = tileH; } while (0);
    clipH = bg->h;
    if (rowStartX < 0) {
        rowStartX += totalW;
    }
    baseY = bg->scrolly % totalH;
    if (baseY < 0) {
        baseY += totalH;
    }
    curY = baseY;
    do { vOff = curY % th; } while (0);
    screenY = bg->y;
    do { do { chunkH = tileH - vOff; } while (0); } while (0);
    if (clipH < chunkH) {
        chunkH = clipH;
    }
    do { mapWm = mapW; } while (0);
    colEndY = curY + clipH;
    tileHi = th;
    rowEndX = rowStartX + clipW;
    params.h = chunkH;
    params.my = -bg->my;
    tileWi = tileW;
    params.y = screenY;

    do {
        s32 withinTileX;
        u16 remCol;
        s32 colPos;
        s32 varS8;
        u16 cell;
        GsCELL *entry;

        withinTileX = rowStartX % tileWi;
        varS8 = bg->x;
        remCol = tileW - withinTileX;
        if (clipW < remCol) {
            remCol = clipW;
        }
        colPos = rowStartX;
        idx = ((colPos % totalW) / tileWi) + (((curY % totalH) / tileHi) * mapWm);
        cell = bg->map->index[idx];
        if (cell != 0xFFFF) {
            entry = &bg->map->base[cell];
            *(u32 *)pk = (u32)(pk + 0x28);
            do { do { pk[3] = 9; } while (0); } while (0);
            params.tpage = blendBits | (entry->tpage & 0x1F);
            params.clut = entry->cba;
            params.x = varS8;
            if (entry->flag & 2) {
                params.u = entry->u;
            } else {
                params.u = entry->u + withinTileX;
            }
            if (entry->flag & 1) {
                sv = ((tileH + entry->v) - chunkH) - vOff;
            } else {
                do { sv = entry->v + vOff; } while (0);
            }
            params.v = sv;
            params.w = remCol;
            params.mx = (colPos - rowStartX) - bg->mx;
            params.flag = entry->flag;
            _mk_spr_packet(pk + 4, &params, &mtx, entry);
            pk += 0x28;
        }

        while (colPos < rowEndX) {
            s32 step;

            idx++;
            if ((idx % mapWm) == 0) {
                idx -= mapWm;
            }
            step = remCol;
            colPos += step;
            remCol = rowEndX - colPos;
            do { do { varS8 += step; } while (0); } while (0);
            if ((u32)tileWi < remCol) {
                remCol = tileW;
            }
            cell = bg->map->index[idx];
            if (cell != 0xFFFF) {
                entry = &bg->map->base[cell];
                *(u32 *)pk = (u32)(pk + 0x28);
                pk[3] = 9;
                params.tpage = blendBits | (entry->tpage & 0x1F);
                params.clut = entry->cba;
                params.x = (varS8 - colPos) + rowStartX;
                if (entry->flag & 2) {
                    params.u = (entry->u + tileW) - remCol;
                } else {
                    params.u = entry->u;
                }
                if (entry->flag & 1) {
                    sv = ((tileH + entry->v) - chunkH) - vOff;
                } else {
                    sv = entry->v + vOff;
                }
                params.v = sv;
                params.w = remCol;
                params.mx = (colPos - rowStartX) - bg->mx;
                params.flag = entry->flag;
                _mk_spr_packet(pk + 4, &params, &mtx, entry);
                pk += 0x28;
            }
        }

        vOff = 0;
        screenY += chunkH;
        curY += chunkH;
        chunkH = colEndY - curY;
        if ((u32)tileHi < chunkH) {
            chunkH = tileH;
        }
        params.my = (curY - baseY) - bg->my;
        params.y = (screenY - curY) + baseY;
        params.h = chunkH;
    } while (curY < colEndY);

    pk -= 0x28;
    slot = pri + otp->offset;
    if (slot < 0) {
        slot = 0;
    }
    bucket = &otp->org[slot];
    pk += 0x28;
    *(u32 *)(pk - 0x28) = *bucket;
    pk[-0x25] = 9;
    *bucket = (u32)GsOUT_PACKET_P;
    ((u8 *)bucket)[3] = 0;
    GsOUT_PACKET_P = pk;
}
